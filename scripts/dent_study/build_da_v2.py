#!/usr/bin/env python3
"""Builds the SBND detector-data-access studies for the technote with the v1.1.0 selection into xml/detector_data_access/sbnd_run1/.
Starts from xml/detector_data_access/sbnd_run1/ and changes (and nothing else):
  MC XML   : main beam MC read from work/sbnd_run1_cvrw.root with `* cvwgt` (as scripts/dent_study/build_xmls.py); every branch of every MC block (beam, dirt, off-beam,
             nonmatched) gains (reco_veto_sbnd_highy_highz == 1) && (reco_cathode_crosser == 0) && (abs(reco_leading_muon_end_x) >= 4) after the cathode cut;
             the detector-variation ratio files are the ones recomputed with the same selection (work/detsys_v2_<observable>.root).
  data XML : the same three terms are added to every data branch (no flash cut on data).
  ini      : area-norm = true and shapeonly = true, pinned seed.
Run from the repository root:  python scripts/dent_study/build_da_v2.py"""

# One-time migration (applied 2026-10-08): the v1.1.0 versions now ARE xml/detector_data_access/sbnd_run1; the pre-migration originals were archived/removed.
# Re-running would transform already-migrated files, so this refuses unless --force is given (then restore the original tree from git history first).
import sys as _sys
if "--force" not in _sys.argv: raise SystemExit("build is a one-time migration that has already been applied; the XMLs in xml/detector_data_access/sbnd_run1 are the source of truth (see xml/MANIFEST.toml). Use --force only after restoring the originals.")
import pathlib, re, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import build_xmls as bx
REPO = bx.REPO; SRC = REPO / "xml" / "detector_data_access" / "sbnd_run1"; DST = REPO / "xml" / "detector_data_access" / "sbnd_run1"
CUTS = "(reco_veto_sbnd_highy_highz == 1) && (reco_cathode_crosser == 0) && (abs(reco_leading_muon_end_x) >= 4)"
STUDIES = [f"{o}_{v}" for o in ("muon_score", "proton_score", "muon_primary_score", "proton_primary_score") for v in ("inclusive", "exclusive", "fine_inclusive", "fine_exclusive", "azimuth", "azimuth8")] + \
          ["vertexx_zoom_inclusive", "vertexz_zoom_inclusive", "muon_endx_zoom_inclusive", "muon_endz_zoom_inclusive", "vertexz_apagap_inclusive", "muon_endz_apagap_inclusive"]

def add_cuts(text):
    n = [0]
    def f(m):
        w = m.group(2)
        w = w.replace("(reco_veto_sbnd_highy_highz == 1) && ", "").replace(" && (reco_veto_sbnd_highy_highz == 1)", "")
        assert "(reco_fiducialize_cathode == 1)" in w, f"no cathode cut anchor: {w[:120]}"
        n[0] += 1
        return f'{m.group(1)}"' + w.replace("(reco_fiducialize_cathode == 1)", "(reco_fiducialize_cathode == 1) && " + CUTS, 1) + '"'
    return re.sub(r'(additional_weight\s*=\s*)"([^"]*)"', f, text), n[0]

# Finer windows around the SBND APA gap (assumed at z = 250 cm; 4 cm bins from 210 to 290 cm), derived from the 10 cm zoom studies.
APAGAP = {"vertexz_apagap_inclusive": "vertexz_zoom_inclusive", "muon_endz_apagap_inclusive": "muon_endz_zoom_inclusive"}
OLD_Z = 'edges="150 160 170 180 190 200 210 220 230 240 250 260 270 280 290 300 310 320 330 340 350"'
NEW_Z = 'edges="' + " ".join(str(z) for z in range(210, 291, 4)) + '"'

def build(study):
    src = APAGAP.get(study, study)
    mc, _ = bx.convert_mc((SRC / f"{src}.xml").read_text(), "sbnd_run1")
    mc, nb = add_cuts(mc)
    mc = re.sub(r"work/detsys_([A-Za-z0-9_]+)\.root", r"work/detsys_v2_\1.root", mc)
    dt, nd = add_cuts((SRC / f"{src}_data.xml").read_text())
    if study == 'muon_endx_zoom_inclusive':   # the cut leaves |x_end| < 4 cm empty: use a central bin of +-5 cm (rather than +-10 cm) so the empty region is not widened by the binning
        old = 'edges="-50 -45 -40 -35 -30 -25 -20 -15 -10 10 15 20 25 30 35 40 45 50"'; new = 'edges="-50 -45 -40 -35 -30 -25 -20 -15 -10 -5 5 10 15 20 25 30 35 40 45 50"'
        assert old in mc and old in dt; mc = mc.replace(old, new); dt = dt.replace(old, new)
    if study in APAGAP:
        assert OLD_Z in mc and OLD_Z in dt; mc = mc.replace(OLD_Z, NEW_Z); dt = dt.replace(OLD_Z, NEW_Z)
    DST.mkdir(parents=True, exist_ok=True)
    (DST / f"{study}.xml").write_text(mc); (DST / f"{study}_data.xml").write_text(dt)
    tag = f"da2_sbnd_run1_{study}"
    (DST / f"{study}_plot.ini").write_text(bx.INI.format(xml=str(DST / f"{study}.xml"), data=str(DST / f"{study}_data.xml"), tag=tag).replace("# Generated by scripts/dent_study/build_xmls.py", "# Generated by scripts/dent_study/build_da_v2.py"))
    return nb, nd

if __name__ == "__main__":
    tb = td = 0
    for s in STUDIES:
        nb, nd = build(s); tb += nb; td += nd
    keys = sorted({m for p in DST.glob("*.xml") for m in re.findall(r"work/(detsys_v2_[A-Za-z0-9_]+)\.root", p.read_text())})
    print(f"{len(STUDIES)} studies; cuts on {tb} MC and {td} data branches; detsys keys: {keys}")
