#!/usr/bin/env python3
"""Regenerates the detector-data-access studies under xml/dent_study/ from the originals in xml/detector_data_access/.

Changes relative to the originals (and nothing else):
  MC XML   : the main beam-MC block reads the CV-reweighted file (work/<det>_cvrw.root) and multiplies cvwgt into every
             branch weight. Dirt / off-beam / nonmatched blocks keep their original files (the reweighted files hold
             only the beam trees).  SBND tree key sbnd_large is unchanged.
  data XML : SBND data selections gain (reco_veto_sbnd_highy_highz == 1). The MC branches of every SBND study already
             apply that veto, but only 4 of the 39 original data XMLs did, which left ~5.8% of data events (the vetoed
             ones) in the data and not in the MC. The flash-PE threshold is trigger emulation and is deliberately NOT added
             to data. ICARUS data selections are left as they were.
  ini      : area-norm = true AND shapeonly = true, pinned seed, 4 threads.
"""
import re, sys, pathlib

REPO = pathlib.Path(__file__).resolve().parents[2]
SRC = REPO / "xml" / "detector_data_access"
DST = REPO / "xml" / "dent_study"

DETS = {  # detector dir -> (main MC tree, cvrw work key, apply SBND veto to data)
    "sbnd_run1": ("events/sbnd_large/selected", "sbnd_run1_cvrw", True),
    "icarus_run2": ("events/icarus_run2/selected", "icarus_run2_cvrw", False),
}
VETO = "(reco_veto_sbnd_highy_highz == 1)"

def convert_mc(text, det):
    tree, key, _ = DETS[det]
    out, n_blocks, n_branches = [], 0, 0
    def block(m):
        nonlocal n_blocks, n_branches
        b = m.group(0)
        hdr = re.match(r"<MCFile[^>]*>", b).group(0)
        if f'treename="{tree}"' not in hdr:
            return b
        n_blocks += 1
        b = re.sub(r'filename="[^"]+"', f'filename="work/{key}.root"', b, count=1)
        def wt(mm):
            nonlocal n_branches
            n_branches += 1
            return f'{mm.group(1)}"({mm.group(2)}) * cvwgt"'
        b = re.sub(r'(additional_weight\s*=\s*)"([^"]*)"', wt, b)
        return b
    text = re.sub(r"<MCFile .*?</MCFile>", block, text, flags=re.S)
    assert n_blocks == 1 and n_branches > 0, f"expected one main-MC block, got {n_blocks} with {n_branches} branches"
    return text, n_branches

def convert_data(text, det):
    if not DETS[det][2]:
        return text, 0
    n = 0
    def add(m):
        nonlocal n
        w = m.group(2)
        if "reco_veto_sbnd_highy_highz" in w:
            return m.group(0)
        n += 1
        # insert right after the cathode cut so the veto sits with the other detector-geometry cuts
        w2 = w.replace("(reco_fiducialize_cathode == 1)", f"(reco_fiducialize_cathode == 1) && {VETO}", 1)
        assert w2 != w, f"no cathode cut to anchor the veto on: {w}"
        return f'{m.group(1)}"{w2}"'
    return re.sub(r'(additional_weight\s*=\s*)"([^"]*)"', add, text), n

INI = """# Generated by scripts/dent_study/build_xmls.py -- do not edit by hand.
# Absolute comparisons are not allowed in this study: area-norm AND shapeonly are always on.
xml = {xml}
tag = {tag}
data = {data}
scale-by-width = true
area-norm = true
shapeonly = true
seed = 20261007
nthread = 4
verbosity = 3
progress = false
log = {tag}.log
file-verbosity = 2

[plot]
"""

def build(det, study, subdir=""):
    sdir = SRC / det / subdir
    mc, data = sdir / f"{study}.xml", sdir / f"{study}_data.xml"
    odir = (REPO / "xml" / "detector_data_access" if det.startswith("icarus") else DST) / det / subdir   # ICARUS has no DENT: its studies live with the detector data access XMLs
    odir.mkdir(parents=True, exist_ok=True)
    t, nb = convert_mc(mc.read_text(), det)
    (odir / f"{study}.xml").write_text(t)
    d, nd = convert_data(data.read_text(), det)
    (odir / f"{study}_data.xml").write_text(d)
    tag = f"dent_{det}_{subdir.strip('/').replace('/', '_') + '_' if subdir else ''}{study}"
    rel = lambda p: str(p)
    (odir / f"{study}_plot.ini").write_text(INI.format(xml=rel(odir / f"{study}.xml"), data=rel(odir / f"{study}_data.xml"), tag=tag))
    return nb, nd

if __name__ == "__main__":
    for det in DETS:
        studies = sorted(p.stem for p in (SRC / det).glob("*.xml") if not p.stem.endswith("_data"))
        sub = sorted(p.stem for p in (SRC / det / "dent_crosser").glob("*.xml") if not p.stem.endswith("_data")) if (SRC / det / "dent_crosser").exists() else []
        tot_b = tot_d = 0
        for s in studies:
            nb, nd = build(det, s); tot_b += nb; tot_d += nd
        for s in sub:
            nb, nd = build(det, s, "dent_crosser"); tot_b += nb; tot_d += nd
        print(f"{det}: {len(studies)+len(sub)} studies, cvwgt on {tot_b} MC branches, veto added to {tot_d} data branches")
