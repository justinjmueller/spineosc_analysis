#!/usr/bin/env python3
"""Generates the inclusive-channel studies for the DENT-improvement study.

See docs/dent_improvement/PLAN.md. Two kinds of study, each for the selections S0 and S2:

    Tier B  production CV with the full systematic suite (DENT in the covariance)
            <study>_s0, <study>_s2
    Tier A  the detvar CV and DENT samples used directly as the MC, MC-statistics covariance only
            tierA_<study>_<sel>_cv, tierA_<study>_<sel>_dent

    S0  fiducial + high-y/z veto (the first study's selection, copied unchanged)
    S2  S0 + reco_cathode_crosser == 0 + |reco_leading_muon_end_x| >= 4 cm (the analysis cuts)

Studies: the muon and proton PID and primary scores (from the first study's inclusive studies) and
the muon and proton (E_calo - E_range)/E_range (from its detector-data-access "dd" studies).

The S2 cuts are inserted after the high-y/z veto term, which every weight in these files already
contains. The MC and data XMLs get the same cuts, and the S2 Tier B MC XML reads detector-variation
ratios recomputed with the same cuts instead of the S0 ratios. The data XMLs are then checked
against the detector-data-access branch whitelist. Run from the repository root:

    python scripts/dent_improvement/build_xmls.py
"""
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "xml" / "dent_study" / "sbnd_run1"
DST = REPO / "xml" / "dent_improvement" / "sbnd_run1"
VETO = "(reco_veto_sbnd_highy_highz == 1)"
S2_CUTS = "(reco_cathode_crosser == 0) && (abs(reco_leading_muon_end_x) >= 4)"
WEIGHT = re.compile(r'(additional_weight\s*=\s*)"([^"]*)"')

# Tier A samples: label -> (tree, work/ file). "cv" and "dent" are the paired detvar samples of the
# DENT study; "nominal" is the production nominal sample that the other detector variations are
# compared with in the detsys calculator; "oldcv"/"olddent" are the older DENT pair (replication).
DETVAR_FILE = "work/sbnd_run1_detvar.root"
TIER_A_SAMPLES = {
    "cv": ("sbnd_detvar_newcv", DETVAR_FILE),
    "dent": ("sbnd_detvar_newdent", DETVAR_FILE),
    "oldcv": ("sbnd_detvar_cv", DETVAR_FILE),
    "olddent": ("sbnd_detvar_dent", DETVAR_FILE),
    "nominal": ("sbnd_large", "work/sbnd_run1_nosyst.root"),
    "chargescale": ("sbnd_detvar_charge_scale", DETVAR_FILE),
    "smear15": ("sbnd_detvar_smear15", DETVAR_FILE),
    "sce0x": ("sbnd_detvar_sce0x", DETVAR_FILE),
    "sce2x": ("sbnd_detvar_sce2x", DETVAR_FILE),
    "nominal_noflash": ("sbnd_large", "work/sbnd_run1_nosyst.root"),
    "wiremodxtheta": ("sbnd_detvar_wiremod_xthetaxw", DETVAR_FILE),
    "wiremodyz": ("sbnd_detvar_wiremod_yz", DETVAR_FILE),
    "mattmodyz": ("sbnd_detvar_mattmod_yz", DETVAR_FILE),
    "gainhigh": ("sbnd_detvar_p5_gain", DETVAR_FILE),
    "gainlow": ("sbnd_detvar_m5_gain", DETVAR_FILE),
}

# The WireMod samples carry no truth information (every true_* branch is NaN) and no flash
# information, so the truth-based subchannel weights and the MC trigger-emulation block select
# nothing; the detsys calculator uses only reco quantities for them. Their Tier A XMLs, and the
# nominal reference they are compared with, use a reco-only selection filling a single branch (the
# area-normalised chi-square only sees the sample total).
RECO_ONLY = {"nominal_noflash", "wiremodxtheta", "wiremodyz"}

# study name -> (source directory, source stem, S0 ratio file stem, S2 ratio file stem)
STUDIES = {
    **{name: (SRC, name, f"detsys_{name.removesuffix('_inclusive')}",
              f"detsys_v2_{name.removesuffix('_inclusive')}")
       for name in ("muon_score_inclusive", "muon_primary_score_inclusive",
                    "proton_score_inclusive", "proton_primary_score_inclusive")},
    **{name: (SRC / "dd", name, f"detsys_dd_{name}", f"detsys_dd_{name}_s2")
       for name in ("muon_calo_csda", "proton_calo_csda")},
}

INI = """# Generated by scripts/dent_improvement/build_xmls.py -- do not edit by hand.
# Area-norm AND shapeonly are always on: absolute comparisons are not allowed.
xml = {xml}
tag = {tag}
data = {data}
scale-by-width = true
area-norm = true
shapeonly = true
seed = 20261007
nthread = 4
verbosity = 3
progress = false
log = {tag}.log
file-verbosity = 2

[plot]
"""


def add_s2(text: str) -> tuple[str, int]:
    """Append the S2 cuts to every additional_weight; return the new text and the count."""
    count = 0

    def one(match):
        nonlocal count
        weight = match.group(2)
        if weight.count(VETO) != 1:
            raise ValueError(f"expected exactly one veto term to anchor on in: {weight[:120]}")
        count += 1
        return f'{match.group(1)}"{weight.replace(VETO, f"{VETO} && {S2_CUTS}", 1)}"'

    return WEIGHT.sub(one, text), count


def swap_ratio_files(text: str, old_stem: str, new_stem: str) -> str:
    """Point an S2 MC XML at the detector ratios recomputed with the S2 selection."""
    old, new = f'filename="work/{old_stem}.root"', f'filename="work/{new_stem}.root"'
    if old not in text:
        raise ValueError(f"no reference to work/{old_stem}.root to swap")
    return text.replace(old, new)


def tier_a(text: str, which: str) -> str:
    """Turn a Tier B MC XML into a Tier A one: one sample as the MC, MC statistics only."""
    tree, filename = TIER_A_SAMPLES[which]
    blocks = re.findall(r"<MCFile .*?</MCFile>", text, flags=re.S)
    main = [b for b in blocks if 'treename="events/sbnd_large/selected"' in b.split(">", 1)[0]]
    if len(main) != 1:
        raise ValueError(f"expected one main MC block, found {len(main)}")
    header = (f'<MCFile treename="events/{tree}/selected" '
              f'filename="{filename}" scale = "1.0" pot="1.0e+19">')
    block = re.sub(r"<MCFile[^>]*>", header, main[0], count=1)
    block = re.sub(r"\s*<friend[^>]*/>", "", block).replace(' * cvwgt"', '"')
    if which in RECO_ONLY:
        block = reco_only(block)
    block = re.sub(r'incl_systematics\s*=\s*"true"', 'incl_systematics      = "false"', block)
    text = re.sub(r"<MCFile .*?</MCFile>\s*", "", text, flags=re.S)
    text = re.sub(r"<HistVarFiles>.*?</HistVarFiles>\s*", "", text, flags=re.S)
    mcstat = ('<variation_list>\n    <allowlist type="mcstat" plotname="MC Stats" '
              'tag="stat,MC Stats">mcstat</allowlist>\n</variation_list>')
    text = re.sub(r"<variation_list>.*?</variation_list>", mcstat, text, flags=re.S)
    return text.rstrip() + "\n\n" + block + "\n"


def reco_only(block: str) -> str:
    """Keep only the reco-level cuts of every weight, and fill a single branch with them."""
    first = True

    def one(match):
        nonlocal first
        weight = match.group(2)
        if first:
            first = False
            weight = "(" + weight[weight.index("(reco_proton_multiplicity"):]
            weight = re.sub(r" && \(\(true_detector == 1.*\)\)\)$", ")", weight)
            weight = re.sub(r"\s*&& \(\(true_detector.*$", ")", weight)
            return f'{match.group(1)}"{weight}"'
        return f'{match.group(1)}"0"'

    block = WEIGHT.sub(one, block)
    # the auxiliary true-L/E and true-energy variables come from truth branches; use constants
    for expression in ("true_baseline / (1000 * true_neutrino_energy)", "true_neutrino_energy"):
        block = block.replace(f"<variable>{expression}</variable>", "<variable>1.0</variable>")
    return block


def write(name: str, text: str, data_name: str, tag: str) -> None:
    """Write one XML and its ini."""
    (DST / f"{name}.xml").write_text(text)
    ini = INI.format(xml=DST / f"{name}.xml", tag=tag, data=DST / f"{data_name}.xml")
    (DST / f"{name}_plot.ini").write_text(ini)


def build(study: str, selection: str, tier_b: bool = True) -> int:
    """Write Tier B and Tier A XMLs for one study and selection; return the weights changed.

    With ``tier_b`` false only the Tier A XMLs are written, so that files read by running jobs
    are left alone.
    """
    source, stem, ratio_s0, ratio_s2 = STUDIES[study]
    DST.mkdir(parents=True, exist_ok=True)
    changed = 0
    texts = {}
    for suffix in ("", "_data"):
        text = (source / f"{stem}{suffix}.xml").read_text()
        if selection == "s2":
            text, n = add_s2(text)
            changed += n
        texts[suffix] = text
    mc = texts[""]
    if selection == "s2":
        mc = swap_ratio_files(mc, ratio_s0, ratio_s2)
    data_name = f"{study}_{selection}_data"
    if tier_b:
        (DST / f"{data_name}.xml").write_text(texts["_data"])
        write(f"{study}_{selection}", mc, data_name, f"dimp_{study}_{selection}")
    for which in TIER_A_SAMPLES:
        write(f"tierA_{study}_{selection}_{which}", tier_a(texts[""], which), data_name,
              f"dimpA_{study}_{selection}_{which}")
    return changed


def main() -> int:
    """Build all studies and run the data-access guard on the data XMLs."""
    tier_b = "--tier-a-only" not in sys.argv
    for study in STUDIES:
        for selection in ("s0", "s2"):
            n = build(study, selection, tier_b)
            note = f": {n} weights given the S2 cuts" if n else ""
            print(f"{study}_{selection}{note}")
    guard = REPO / "scripts" / "dent_improvement" / "check_data_access.py"
    data_xmls = sorted(str(p) for p in DST.glob("*_data.xml"))
    return subprocess.run([sys.executable, str(guard), *data_xmls]).returncode


if __name__ == "__main__":
    sys.exit(main())
