#!/usr/bin/env python3
"""Regenerates xml/systematics/systematics_suite.xml from xml/contours/contours_recoe.xml so the fractional-systematics jobs
(jobs/systematics/systs_{reco,true}.ini -> plotting/systematics.ipynb) always carry the current analysis (cuts, cvwgt inputs, POTs, systematic suite).
The only intended differences from contours_recoe.xml:
  * the true-energy bins are PLOTTED (no plot="false") so --fit-variable 2 can produce the true-energy breakdown;
  * a header that says what this file is for."""
import pathlib, re
R = pathlib.Path(__file__).resolve().parents[1]
src = (R / "xml/contours/contours_recoe.xml").read_text()
src = re.sub(r"<!--\n=+\n= Contours, 1D reconstructed-energy fit variable.*?-->", "", src, count=1, flags=re.S)
n_before = src.count('plot="false"')
src = re.sub(r'(<bins unit="True E \[GeV\]"[^>]*?)\s+plot="false"\s*/>', r'\1/>', src)
assert src.count('plot="false"') == n_before - 2, "expected to un-hide exactly the two True E bins"
head = '''<?xml version="1.0" ?>

<!--
=====================================================
= Systematics suite (generated)                     =
=====================================================

GENERATED by scripts/systematics_suite_from_recoe.py from xml/contours/contours_recoe.xml; do not edit by hand. Re-run the script
after changing contours_recoe.xml.

Used by jobs/systematics/systs_reco.ini (--fit-variable 0, reconstructed energy) and systs_true.ini (--fit-variable 2, true energy), whose
PROfit plot outputs feed plotting/systematics.ipynb. PROfit only writes the fractional-systematics tree for the fitting variable, so each space
needs its own fit-variable. Layout: var0 RecoE (1D, both channels), var1 True L/E (model-reserved, cannot be fit), var2 True E.
The single difference from contours_recoe.xml is that the true-energy bins are plotted (no plot="false").
-->
'''
body = src.split("?>", 1)[1] if src.lstrip().startswith("<?xml") else src
(R / "xml/systematics/systematics_suite.xml").write_text(head + body.lstrip("\n"))
print("wrote xml/systematics/systematics_suite.xml")
