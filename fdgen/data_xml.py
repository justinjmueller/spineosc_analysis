#!/usr/bin/env python3
"""Build the PROfit "data" XML that reads one fdgen scenario as fake data.

  .venv/bin/python -m fdgen.data_xml output/fdgen/closure_2d <scenario id> -o xml/fakedata/data/fdgen_closure_2d_osc_a.xml

Same recipe as scripts/fakedata_data_xml.py: the MC XML supplies <mode>, <detector>, <model> and the channels (each with
the single subchannel "data"); every MC branch becomes a "data" branch with model_rule 0, so nothing is oscillated or
reweighted by PROfit itself. The scenario enters through the `mystery` friend tree written by fdgen.generate:
  Asimov : additional_weight * mysterywgtNN
  Poisson: mysterycntNN / pot_scale   (PROfit multiplies every weight by pot_scale, so the net weight is the integer count)
The slim files hold a copy of `selected` plus the friend tree `<tree>_mysteryTree`, entry-aligned (PROfit ignores a <friend> filename, so both must be in one file).
"""
import argparse
import os
import re

import yaml

from . import xmlinfo

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def build(outdir, scenario_id, use_counts=None, keydir=None):
    outdir = os.path.abspath(outdir)
    manifest = yaml.safe_load(open(os.path.join(keydir or outdir, "manifest.yaml")))
    key = yaml.safe_load(open(os.path.join(keydir or outdir, "KEY.yaml")))
    idx = next(s["index"] for s in key["scenarios"] if s["id"] == scenario_id)
    counts = manifest["poisson"] if use_counts is None else use_counts
    xml = os.path.join(REPO, manifest["mc_xml"])
    s = open(xml).read()
    info = xmlinfo.load(xml)
    pot_scale = {f["treename"]: xmlinfo.pot_scale(info, f) for f in info["files"]}
    produced = {f["tree"]: f["file"] for f in manifest["files"]}

    out = ['<?xml version="1.0" ?>\n',
           f"<!--\nfdgen fake data (generated by fdgen/data_xml.py): dataset {manifest['name']}, scenario index {idx:02d}, "
           f"{'Poisson counts' if counts else 'Asimov weights'}.\nNo systematics, no real beam data.\n-->\n",
           re.search(r'<mode name="[^"]*"\s*/>', s).group(0) + "\n"]
    out += [m.group(0) + "\n" for m in re.finditer(r'<detector name="[^"]*"\s+pot="[^"]*"\s*/>', s)]
    out.append(re.search(r'<model tag=.*?</model>', s, re.S).group(0) + "\n")
    for m in re.finditer(r'<channel name=.*?</channel>', s, re.S):
        block = re.sub(r'\s*<subchannel [^>]*/>', "", m.group(0))
        out.append(block.replace("</channel>", '    <subchannel name="data" plotname="Data" color="#000000"/>\n\n</channel>') + "\n")
    for m in re.finditer(r'<MCFile .*?</MCFile>', s, re.S):
        block = m.group(0)
        head = re.search(r'<MCFile[^>]*>', block).group(0)
        tree = xmlinfo.attrs(head)["treename"]
        if tree not in produced:
            raise SystemExit(f"{tree}: no fdgen output in {outdir} (regenerate without --only)")
        slim = os.path.join(outdir, produced[tree])
        new = [head.replace(xmlinfo.attrs(head)["filename"], slim), f'    <friend treename="{tree}_mysteryTree" />']
        for b in re.finditer(r'<branch\s(?:[^>"]|"[^"]*")*>.*?</branch>', block, re.S):
            bt = b.group(0)
            ba = xmlinfo.attrs(re.match(r'<branch\s(?:[^>"]|"[^"]*")*>', bt).group(0))
            sub = re.match(r'(nu_[A-Za-z0-9]+_(?:ccqelike|nproton|inclusive))_\w+', ba["associated_subchannel"]).group(1) + "_data"
            if counts:
                # the selection factor (0 or cvwgt-weighted membership) was already folded into lambda, so the count is the weight;
                # membership is restated through the selection so events outside the branch stay at 0
                sel = f"(({ba['additional_weight']}) != 0)"
                weight = f"{sel} * mysterycnt{idx:02d} / {pot_scale[tree]:.12g}"
            else:
                weight = f"({ba['additional_weight']}) * mysterywgt{idx:02d}"
            variables = "".join(f"        {v}\n" for v in re.findall(r'<variable(?:2D)?>.*?</variable(?:2D)?>', bt, re.S))
            new.append(f'    <branch\n        associated_subchannel = "{sub}"\n        model_rule            = "0"\n'
                       f'        additional_weight     = "{weight}"\n    >\n{variables}    </branch>')
        new.append("</MCFile>\n")
        out.append("\n".join(new))
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("outdir")
    ap.add_argument("scenario")
    ap.add_argument("--keydir", help="where KEY.yaml/manifest.yaml are (dataset.keydir), default the dataset directory")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()
    text = build(args.outdir, args.scenario, keydir=args.keydir)
    open(args.output, "w").write(text)
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
