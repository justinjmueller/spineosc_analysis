"""
Fake-data fits in the 2D configuration: absorption by the nuisance parameters.

Replaces ``plotting/fakedata_2d_studies.ipynb`` (generated by
``plotting/scripts/build_fakedata_2d_notebook.py``). It reads the global fits of the 2D
campaign ``runs/fakedata_2d`` through the library ``plotting/scripts/fd2d.py`` (imported,
not copied; see also ``docs/fakedata_review/STUDY_DESIGN.md``) and makes the tables,
figures and headline numbers quoted in the fake-data report.

Analyses (all ``xml/contours/contours_base.xml``, full systematics suite, 2D ``RecoE;pn``
in the single-proton channel): **b** = single-proton and multi-proton combined (both
channels fit together), **1p** = single-proton channel only, **Np** = multi-proton
channel only, **m** = merged (one inclusive 2D ``RecoE;pn`` histogram, no split by proton
multiplicity). Each fake dataset is fit with the oscillation parameters fixed (null) and
floating (oscillation), and the test statistic is
:math:`\\Delta\\chi^2=\\chi^2_{\\rm null}-\\chi^2_{\\rm osc}`. Fake data are MC only (no real
beam data anywhere): the CV MC reweighted by a reBruce dial (separate data XML, route
``ds``, so the nuisance parameters have no knob for it), or PROfit's own fake data
(``--use-fake-data``, route ``fd``) for the IceCube points, Poisson throws and the
technote-style QE-interference and spectral-function injections.

Inputs: ``runs/fakedata_2d/jobs_2d.txt`` (the campaign's job list), the fit outputs
described in ``fd2d.py`` and the job markers in ``runs/fakedata_2d/done``.

Sections (``--list-sections``; select with ``--section <name|number>``, repeatable; default
is all, in order). Each prints its tables, writes CSV tables to ``<output>/tables`` and
adds numbers to the headline dictionary, merged into ``<output>/tables/headline.json``:

====  ===============  =====================================================
 0    integrity        job return codes; fits with negative Delta chi2
 1    closure          closure and cross-validation of the two routes
 2    technote         comparison with the technote's fake-data studies
 3    poisson          Poisson throws: null distribution of Delta chi2
 4    absorption       can the nuisance parameters absorb each dial?
 5    channels         what fitting one channel changes
 6    constraints      constraints on the nuisance parameters
 7    recovery         recovering the injected oscillation point
 8    pulls            pulls (overlays, largest pull per dataset)
 9    knob-pulls       pull of the injected knob (knob in the fit)
10    injection-size   size of the injected effect; what "absorbed" means
11    bounds           nuisance parameters at their bounds
12    qeint-family     QE interference with the whole dial family excluded
13    false-signal     where the oscillation fit lands for non-oscillation data
14    seeds            minimiser robustness: refits with different seeds
====  ===============  =====================================================

Figures are written to ``plotting/fakedata_2d_figures`` (git-ignored; ``--output`` to
change): ``poisson_null``, ``dials_heatmap``, ``channel_split``, ``constraint_widths``,
``injection_size`` and ``pulls/pulls_<fix|free>_<route>_<stem>``, in ``--format``.

Usage (mutools environment)::

    /Users/mueller/Projects/mutools/.venv/bin/python plotting/studies/fakedata_2d.py \\
        --section closure --section poisson
"""

