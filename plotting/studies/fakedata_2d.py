def section_integrity(ctx: Context) -> None:
    """
    Integrity of the campaign.

    Every job's return codes (code 99 = an injected systematic was not confirmed in the
    log, i.e. the run silently fell back to plain Asimov). A fit with Delta chi2 < 0 means
    the oscillation fit found a worse minimum than the null fit (minimizer failure).

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2, camp = f2_lib(), ctx.camp
    st, bad = f2.job_status(), f2.failures()
    print(
        "completed job markers:", len(st), "of", len(camp.jobs),
        "| with a nonzero return code:", len(bad),
    )  # fmt: skip
    if len(bad):
        print(bad.to_string(index=False))
    neg = []
    for route, stems in (("fd", camp.fd), ("ds", camp.ds)):
        for cfg in f2.CONFIGS:
            for s in stems:
                d = f2.delta_chi2(route, cfg, s)
                if np.isfinite(d) and d < -1e-3:
                    neg.append((route, cfg, s, d))
    print("fits with Delta chi2 < 0 (oscillation fit worse than null):", len(neg))
    for n in neg[:20]:
        print("  ", n)
    ctx.head.update(
        n_jobs_done=int(len(st)), n_jobs_expected=int(len(camp.jobs)),
        n_failed=int(len(bad)), n_negative_dchi2=len(neg),
    )  # fmt: skip


def section_closure(ctx: Context) -> None:
    """
    Closure and cross-validation of the two routes.

    * The no-injection control must give chi2 close to 0 in both routes and all analyses.
    * PROfit's native IceCube injection (``--use-fake-data --inject``) and the
      per-event-baseline dial ``osc_ic2024_pebl_*`` (separate data XML) describe the same
      physics and should agree. The fixed-110 m dial ``osc_ic2024_*`` is expected to differ
      (ICARUS).

    Writes ``closure.csv`` and ``route_crosscheck.csv``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2 = f2_lib()
    cfgs = f2.CONFIGS
    rows = []
    for cfg in cfgs:
        for route, stem in (("fd", "ctrl"), ("ds", "ctrl")):
            p = f2.pair(route, cfg, stem)
            if p:
                rows.append(
                    {
                        "route": route, "config": cfgs[cfg],
                        "chi2 null": p[0]["chi2"], "chi2 osc": p[1]["chi2"],
                    }
                )  # fmt: skip
    clos = pd.DataFrame(rows)
    print(clos.to_string(index=False))
    ctx.save_table(clos, "closure.csv", index=False)

    pairs = [
        ("phys_lo", "osc_ic2024_pebl_dm2lo", "osc_ic2024_dm2lo"),
        ("phys_best", "osc_ic2024_pebl_bestfit", "osc_ic2024_bestfit"),
        ("phys_hi", "osc_ic2024_pebl_dm2hi", "osc_ic2024_dm2hi"),
    ]
    rows = []
    for nat, pebl, fixed in pairs:
        for cfg in cfgs:
            r = {
                "point": nat,
                "config": cfgs[cfg],
                "dchi2 native (fd)": f2.delta_chi2("fd", cfg, nat),
                "dchi2 per-event-L dial (ds)": f2.delta_chi2("ds", cfg, pebl),
                "dchi2 fixed-110m dial (ds)": f2.delta_chi2("ds", cfg, fixed),
            }
            pn, pp = f2.pair("fd", cfg, nat), f2.pair("ds", cfg, pebl)
            r["chi2 null native"] = pn[0]["chi2"] if pn else np.nan
            r["chi2 null per-event-L dial"] = pp[0]["chi2"] if pp else np.nan
            rows.append(r)
    xr = pd.DataFrame(rows)
    show(xr)
    ctx.save_table(xr, "route_crosscheck.csv", index=False)
    ctx.head["route_ratio_b"] = [
        float(r["dchi2 per-event-L dial (ds)"] / r["dchi2 native (fd)"])
        for _, r in xr[xr.config == cfgs["b"]].iterrows()
        if np.isfinite(r["dchi2 native (fd)"]) and r["dchi2 native (fd)"] > 0
    ]


def section_technote(ctx: Context) -> None:
    """
    Comparison with the technote's fake-data studies (combined analysis).

    The technote quotes one Poisson throw, QE interference +-1 sigma and spectral function
    +-1 sigma with the injected knob left in the fit, and the three IceCube points. This
    repeats the same studies in the current production (v1.1.0 selection; the technote
    numbers predate it) in the combined analysis, plus the variants with the injected knob
    excluded from the fit. Poisson: mean over ten throws (seeds 1-10) rather than one
    throw. Writes ``technote_comparison_b.csv``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2, camp = f2_lib(), ctx.camp

    def line(label: str, cfg: str, stem: str, route: str = "fd") -> dict | None:
        p = f2.pair(route, cfg, stem)
        if p is None:
            return None
        return {"study": label, "chi2 null": p[0]["chi2"], "chi2 osc": p[1]["chi2"],
                "dchi2": dchi2(p)}  # fmt: skip

    rows = []
    cfg = "b"
    pois = [p for p in (f2.pair("fd", cfg, s) for s in camp.pois) if p]
    if pois:
        n0 = np.array([p[0]["chi2"] for p in pois])
        n1 = np.array([p[1]["chi2"] for p in pois])
        rows.append(
            {
                "study": f"Poisson throws (n={len(pois)}, mean)",
                "chi2 null": n0.mean(),
                "chi2 osc": n1.mean(),
                "dchi2": (n0 - n1).mean(),
                "technote chi2 null": TECHNOTE["poisson"][0],
                "technote dchi2": TECHNOTE["poisson"][2],
            }
        )
    variants = (("infit", "knob in fit (as technote)"), ("excl", "knob excluded"))
    for s, lab in (
        ("qeint_p1", "QE interference +1 sigma"),
        ("qeint_m1", "QE interference -1 sigma"),
        ("specf_p1", "Spectral function +1 sigma"),
        ("specf_m1", "Spectral function -1 sigma"),
    ):
        for var, tag in variants:
            r = line(f"{lab}, {tag}", cfg, f"{s}_{var}")
            if r:
                if var == "infit":
                    r["technote chi2 null"], r["technote dchi2"] = TECHNOTE[s][0], TECHNOTE[s][2]
                rows.append(r)
    for s, lab in (
        ("phys_lo", "IceCube dm2 = 2.07, s22 = 0.116"),
        ("phys_best", "IceCube dm2 = 3.5, s22 = 0.16"),
        ("phys_hi", "IceCube dm2 = 12.1, s22 = 0.187"),
    ):
        r = line(lab, cfg, s)
        if r:
            r["technote dchi2"] = TECHNOTE_ICE[s]
            rows.append(r)
    tn = pd.DataFrame(rows)
    show(tn)
    ctx.save_table(tn, "technote_comparison_b.csv", index=False)
    for s in ICE:
        ctx.head[f"dchi2_{s}"] = {c: float(f2.delta_chi2("fd", c, s)) for c in f2.CONFIGS}


def section_poisson(ctx: Context) -> None:
    """
    Poisson fluctuations: the null distribution of Delta chi2.

    Ten throws of the CV (seeds 1-10) for each analysis. Under Wilks' theorem
    Delta chi2 follows a chi2 distribution with 2 dof (CDF dotted). Writes
    ``poisson_null`` and ``poisson_null.csv``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2 = f2_lib()
    cfgs, cc = f2.CONFIGS, f2.CFG_COLOR
    fig, axes = plt.subplots(1, 2, figsize=(14, 4.6))
    rows = []
    for cfg in cfgs:
        ps = [p for p in (f2.pair("fd", cfg, s) for s in ctx.camp.pois) if p]
        if not ps:
            continue
        d = np.array([dchi2(p) for p in ps])
        n0 = np.array([p[0]["chi2"] for p in ps])
        xs = np.sort(d)
        axes[0].step(
            xs, np.arange(1, len(xs) + 1) / len(xs), where="post", color=cc[cfg],
            label=f"{cfgs[cfg]} (n = {len(xs)})",
        )  # fmt: skip
        axes[1].hist(n0, bins=8, histtype="step", color=cc[cfg], label=cfgs[cfg])
        ks = stats.kstest(d, stats.chi2(2).cdf)
        rows.append(
            {
                "config": cfgs[cfg],
                "throws": len(d),
                "mean dchi2": d.mean(),
                "std dchi2": d.std(ddof=1),
                "max dchi2": d.max(),
                "fraction with Wilks p<0.05": float(np.mean([f2.wilks_p(x) < 0.05 for x in d])),
                "mean chi2 null": n0.mean(),
                "bins": f2.NBINS[cfg],
                "KS p vs chi2(2)": ks.pvalue,
            }
        )
    xx = np.linspace(0, 12, 200)
    axes[0].plot(xx, stats.chi2(2).cdf(xx), "k:", label=r"$\chi^2$, 2 dof")
    axes[0].set_xlabel(r"$\Delta\chi^2=\chi^2_{\rm null}-\chi^2_{\rm osc}$")
    axes[0].set_ylabel("cumulative fraction")
    axes[0].legend(fontsize=9)
    axes[1].set_xlabel(r"null-fit $\chi^2$")
    axes[1].set_ylabel("throws")
    axes[1].legend(fontsize=9)
    fig.tight_layout()
    ctx.save_fig(fig, "poisson_null")
    pn = pd.DataFrame(rows)
    print(pn.round(3).to_string(index=False))
    ctx.save_table(pn, "poisson_null.csv", index=False)
    ctx.head["poisson"] = pn.to_dict(orient="records")


def absorption_table(route: str, stems: list[str]) -> pd.DataFrame:
    """
    Null-fit chi2 and Delta chi2 of each dataset in each analysis.

    Parameters
    ----------
    route : str
        ``fd`` or ``ds``.
    stems : list of str
        Dataset stems.

    Returns
    -------
    pandas.DataFrame
        Columns ``dataset``, ``chi2 null <cfg>``, ``dchi2 <cfg>``; nan where a fit is missing.
    """
    f2 = f2_lib()
    rows = []
    for s in stems:
        r = {"dataset": s}
        for cfg in f2.CONFIGS:
            p = f2.pair(route, cfg, s)
            r[f"chi2 null {cfg}"] = p[0]["chi2"] if p else np.nan
            r[f"dchi2 {cfg}"] = dchi2(p) if p else np.nan
        rows.append(r)
    return pd.DataFrame(rows)


def heat(ax: plt.Axes, m: np.ndarray, title: str, cols: list[str]) -> None:
    """
    Log-coloured heat map with the values annotated.

    Parameters
    ----------
    ax : matplotlib.axes.Axes
        Target axes.
    m : np.ndarray
        Matrix of chi2 values (rows datasets, columns analyses).
    title : str
        Panel title.
    cols : list of str
        Column labels.
    """
    ax.imshow(np.log10(np.clip(m, 1e-3, None)), aspect="auto", cmap="viridis", vmin=-2, vmax=2.5)
    for i in range(m.shape[0]):
        for j in range(m.shape[1]):
            if np.isfinite(m[i, j]):
                ax.text(
                    j, i, f"{m[i, j]:.2g}", ha="center", va="center", fontsize=6,
                    color="w" if np.log10(max(m[i, j], 1e-3)) < 1 else "k",
                )  # fmt: skip
    ax.set_xticks(range(len(cols)))
    ax.set_xticklabels(cols, rotation=20, ha="right", fontsize=8)
    ax.set_title(title, fontsize=11)


def section_absorption(ctx: Context) -> None:
    """
    Can the nuisance parameters absorb each dial? (data-XML route, dial excluded from the fit)

    The null-fit chi2 is how far the fake data sit from the best nuisance-only description
    (0 = fully absorbed); Delta chi2 is what the oscillation parameters add; both for each
    analysis. Writes ``dials_absorption.csv`` and ``dials_heatmap``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2, camp = f2_lib(), ctx.camp
    dt = absorption_table("ds", camp.ds)
    show(dt, rows=100)
    ctx.save_table(dt, "dials_absorption.csv", index=False)
    ctx.head["dials_top_b"] = (
        dt.sort_values("chi2 null b", ascending=False)
        .head(8)[["dataset", "chi2 null b", "dchi2 b", "chi2 null 1p", "chi2 null Np"]]
        .to_dict(orient="records")
    )
    ctx.head["n_dials_absorbed_b"] = int((dt[dt.dataset != "ctrl"]["chi2 null b"] < 1.0).sum())
    ctx.head["n_dials"] = int(len(camp.dials))

    order = [s for s in camp.ds if s != "ctrl"]
    fig, axes = plt.subplots(1, 2, figsize=(11, max(7, 0.28 * len(order))), sharey=True)
    indexed = dt.set_index("dataset")
    titles = (r"null-fit $\chi^2$", r"$\Delta\chi^2$ (null $-$ oscillation fit)")
    for ax, kind, title in zip(axes, ("chi2 null", "dchi2"), titles, strict=True):
        m = np.array([[indexed.loc[s, f"{kind} {c}"] for c in f2.CONFIGS] for s in order])
        heat(ax, m, title, [f2.CONFIGS[c] for c in f2.CONFIGS])
    axes[0].set_yticks(range(len(order)))
    axes[0].set_yticklabels([s.replace("_", " ") for s in order], fontsize=7)
    fig.tight_layout()
    ctx.save_fig(fig, "dials_heatmap")


def section_channels(ctx: Context) -> None:
    """
    What fitting one channel changes.

    For every dataset: how large is the null-fit chi2 (and Delta chi2) in the
    single-channel analyses relative to the combined one, and is the combined analysis more
    than the sum of its parts (which would signal that combining channels breaks degeneracies
    between nuisance parameters)? Writes ``channel_comparison.csv`` and ``channel_split``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2, camp = f2_lib(), ctx.camp
    allrows = []
    for route, stems in (("fd", PHYS + camp.tech), ("ds", camp.dials)):
        for s in stems:
            pb, p1, pn = (f2.pair(route, c, s) for c in ("b", "1p", "Np"))
            if not (pb and p1 and pn):
                continue
            cb, c1, cn = pb[0]["chi2"], p1[0]["chi2"], pn[0]["chi2"]
            pm = f2.pair(route, "m", s)
            allrows.append(
                {
                    "chi2 null m": pm[0]["chi2"] if pm else np.nan,
                    "dchi2 m": dchi2(pm) if pm else np.nan,
                    "route": route,
                    "dataset": s,
                    "chi2 null b": cb,
                    "chi2 null 1p": c1,
                    "chi2 null Np": cn,
                    "(1p+Np)/b": (c1 + cn) / cb if cb > 1e-6 else np.nan,
                    "m/b": (pm[0]["chi2"] / cb) if (pm and cb > 1e-6) else np.nan,
                    "frac 1p of 1p+Np": c1 / (c1 + cn) if c1 + cn > 1e-9 else np.nan,
                    "dchi2 b": dchi2(pb),
                    "dchi2 1p": dchi2(p1),
                    "dchi2 Np": dchi2(pn),
                }
            )
    ch = pd.DataFrame(allrows)
    if ch.empty:
        print("channels: no dataset has all of the b, 1p and Np fits")
        return
    show(ch, ".3g", rows=120)
    ctx.save_table(ch, "channel_comparison.csv", index=False)
    sig = ch[ch["chi2 null b"] > 1.0]
    ctx.head["channel_ratio_median"] = float(sig["(1p+Np)/b"].median()) if len(sig) else None
    ctx.head["merged_over_combined_median"] = (
        float(sig["m/b"].median()) if len(sig) and sig["m/b"].notna().any() else None
    )
