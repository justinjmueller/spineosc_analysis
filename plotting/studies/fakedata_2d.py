def section_constraints(ctx: Context) -> None:
    """
    Constraints on the nuisance parameters.

    With the CV as fake data, the posterior width of each nuisance parameter measures the
    constraint (prior = 1). **Caveat found in independent review:** the MCMC chains are short
    (20000 steps) and highly autocorrelated (lag-1 autocorrelation about 0.995), so a single
    run's width is noisy. We therefore use the four runs that have the same fake data (the
    control, in both routes, null and oscillation fit) per analysis, quote their mean, and
    only call a difference between analyses real if it exceeds three standard errors of the
    repeatability. Posterior means are not used; pulls are the optimizer's best-fit values.
    Writes ``constraint_widths.csv``, ``constraint_width_repeatability.csv`` and
    ``constraint_widths``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2 = f2_lib()
    cfgs, cc = f2.CONFIGS, f2.CFG_COLOR
    wr = {}
    for cfg in cfgs:
        cols = []
        for route, var in CONTROL_RUNS:
            if f2.available(route, cfg, var, "ctrl"):
                f = f2.read_fit(route, cfg, var, "ctrl")
                cols.append(pd.Series({n: f["sigma"].get(n, np.nan) for n in f2.nuisance_names(f)}))
        if cols:
            wr[cfg] = pd.concat(cols, axis=1)
    if set(wr) != set(cfgs):
        print("constraints: control fits missing for", sorted(set(cfgs) - set(wr)))
        return
    m = pd.DataFrame({c: wr[c].mean(axis=1) for c in cfgs})
    sd = pd.DataFrame({c: wr[c].std(axis=1) for c in cfgs})
    rep = {c: float(sd[c].mean()) for c in cfgs}
    print(
        "repeatability: mean over parameters of the std across the 4 control runs:",
        {c: round(v, 3) for c, v in rep.items()},
    )
    for c in cfgs:
        print(
            f"  {cfgs[c]:34s} median width {m[c].median():.3f}   below 0.5 sigma: "
            f"{(m[c] < 0.5).sum():3d}   below 0.8 sigma: {(m[c] < 0.8).sum():3d}"
        )
    se = np.sqrt((sd["1p"] ** 2 + sd["Np"] ** 2) / 4)
    d = m["1p"] - m["Np"]
    sig = d[(d.abs() > 0.15) & (d.abs() > 3 * se)].sort_values()
    print("single-proton vs multi-proton width difference > 0.15 and > 3 s.e.:")
    print(sig.round(3).to_string())
    comb = m["b"] < m[["1p", "Np"]].min(axis=1) - 0.05
    print(
        "combining tightens by > 0.05 relative to the better channel:",
        int(comb.sum()), f"(repeatability ~{rep['b']:.2f}, so treat as indicative)",
    )  # fmt: skip
    ctx.save_table(m, "constraint_widths.csv")
    ctx.save_table(sd, "constraint_width_repeatability.csv")
    ctx.head["width_repeatability"] = rep
    ctx.head["width_median"] = {c: float(m[c].median()) for c in cfgs}
    ctx.head["width_lt05"] = {c: int((m[c] < 0.5).sum()) for c in cfgs}
    ctx.head["width_sig_1p_tighter"] = [n for n, v in sig.items() if v < 0]
    ctx.head["width_sig_Np_tighter"] = [n for n, v in sig.items() if v > 0]

    fig, axes = plt.subplots(1, 2, figsize=(14, 5.4))
    ax = axes[0]
    ax.errorbar(m["1p"], m["Np"], xerr=sd["1p"], yerr=sd["Np"], fmt="o", ms=3, lw=0.5, color="C2")
    ax.plot([0, 1.2], [0, 1.2], "k--", lw=0.8)
    for n in sig.index:
        ax.annotate(
            n, (m.loc[n, "1p"], m.loc[n, "Np"]), fontsize=8, xytext=(3, 3),
            textcoords="offset points",
        )  # fmt: skip
    ax.set_xlabel("mean posterior width, single-proton only")
    ax.set_ylabel("mean posterior width, multi-proton only")
    ax = axes[1]
    order = m["b"].sort_values().index
    for c in cfgs:
        ax.errorbar(
            np.arange(len(order)), m.loc[order, c].values, yerr=sd.loc[order, c].values,
            fmt=".", ms=4, lw=0.4, color=cc[c], label=cfgs[c],
        )  # fmt: skip
    ax.axhline(1, color="0.5", ls="--", lw=0.8)
    ax.set_xlabel("nuisance parameter, sorted by combined constraint")
    ax.set_ylabel("posterior width [prior sigma]")
    ax.legend(fontsize=8)
    fig.tight_layout()
    ctx.save_fig(fig, "constraint_widths")


