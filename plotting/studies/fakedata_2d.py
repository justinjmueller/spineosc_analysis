def resolve_sections(requested: list[str] | None) -> list[Section]:
    """
    Map ``--section`` values (names or numbers) to sections.

    Parameters
    ----------
    requested : list of str or None
        Values given on the command line; None selects every section.

    Returns
    -------
    list of Section
        The selected sections, in the order requested.

    Raises
    ------
    SystemExit
        If a value matches no section.
    """
    if not requested:
        return list(SECTIONS)
    out = []
    for item in requested:
        match = [s for s in SECTIONS if item == s.name or item == str(s.number)]
        if not match:
            raise SystemExit(f"unknown section {item!r}; use --list-sections")
        out.append(match[0])
    return out


def write_headline(ctx: Context) -> None:
    """
    Merge this run's headline numbers into ``<output>/tables/headline.json``.

    Merging (rather than overwriting) keeps the numbers of sections that were not run.

    Parameters
    ----------
    ctx : Context
        Run context holding the headline dictionary.
    """
    if not ctx.head:
        return
    path = ctx.tables / "headline.json"
    merged = json.loads(path.read_text()) if path.exists() else {}
    merged.update(ctx.head)
    ctx.tables.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(merged, indent=1, default=float))
    print(f"headline numbers merged into {path}")


def build_parser() -> argparse.ArgumentParser:
    """
    Command-line parser.

    Returns
    -------
    argparse.ArgumentParser
        Parser with the common study options plus ``--section`` and ``--list-sections``.
    """
    parser = common.base_parser(__doc__)
    parser.set_defaults(output=OUTPUT)
    parser.add_argument("--section", action="append", help="section name or number (repeatable)")
    parser.add_argument("--list-sections", action="store_true", help="list sections and exit")
    return parser


def main(argv: list[str] | None = None) -> None:
    """
    Run the selected sections.

    Parameters
    ----------
    argv : list of str, optional
        Command-line arguments; defaults to ``sys.argv[1:]``.
    """
    args = build_parser().parse_args(argv)
    if args.list_sections:
        for s in SECTIONS:
            print(f"{s.number:2d}  {s.name:15s} {s.title}")
        return
    sections = resolve_sections(args.section)
    common.configure_style(args.format)
    camp = load_campaign()
    print(
        "datasets via data XML:", len(camp.ds), "| fd stems:", len(camp.fd),
        "| expected job lines:", len(camp.jobs),
    )  # fmt: skip
    ctx = Context(args=args, camp=camp)
    for s in sections:
        print(f"\n== {s.number} {s.name}: {s.title}", file=sys.stderr)
        s.func(ctx)
    write_headline(ctx)


if __name__ == "__main__":
    main()
