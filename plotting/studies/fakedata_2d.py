def projected_counts(h: dict, prefix: str, detector: int, channel: int) -> np.ndarray:
    """
    Counts per bin of one projected histogram of a PROfit ``global`` histogram file.

    PROfit was run with ``--scale-by-width``: ``bin_content`` is events per unit RecoE, so
    it is multiplied back by the bin width to get counts.

    Parameters
    ----------
    h : dict
        The ``hist1d`` tree as numpy arrays (``prefix`` as strings).
    prefix : str
        ``DATA`` or ``CV``.
    detector, channel : int
        Detector and channel indices.

    Returns
    -------
    np.ndarray
        Counts per bin.
    """
    m = (h["prefix"] == prefix) & (h["detector"] == detector) & (h["channel"] == channel)
    _, o = np.unique(h["bin_index"][m], return_index=True)
    w = (h["bin_high_edge"][m] - h["bin_low_edge"][m])[o]
    return h["bin_content"][m][o] * w


def stat_chi2(route: str, cfg: str, stem: str) -> float:
    """
    Stat-only chi2 = sum (D - C)^2 / D of the fake data D against the CV prediction C.

    Computed in the projected spectra that PROfit stores (the 16+14 reco-energy bins per
    detector), summed over three detectors and two channels.

    Parameters
    ----------
    route : str
        ``fd`` or ``ds``.
    cfg : str
        Analysis key.
    stem : str
        Dataset stem.

    Returns
    -------
    float
        The chi2, or nan if the histogram file does not exist.
    """
    f2 = f2_lib()
    tag = f2._paths(route, cfg, "fix", stem)[0]
    p = f2.RUN / f"{tag}_PROglobal_histograms.root"
    if not p.exists():
        return np.nan
    h = uproot.open(p)["hist1d"].arrays(library="np")
    h["prefix"] = np.asarray(h["prefix"]).astype(str)
    tot = 0.0
    for det in range(3):
        for ch in range(2):
            d, c = projected_counts(h, "DATA", det, ch), projected_counts(h, "CV", det, ch)
            if len(d):
                tot += float(np.sum((d - c) ** 2 / np.maximum(d, 1e-9)))
    return tot


def section_injection_size(ctx: Context) -> None:
    """
    Size of the injected effect, and what "absorbed" means.

    The null-fit chi2 alone is not normalised to how large the injection is (the stat-only
    distortions span about three orders of magnitude). This computes the stat-only
    chi2 = sum (D - C)^2 / D of the fake data D against the CV prediction C in the projected
    spectra that PROfit stores (the 16+14 reco-energy bins per detector, i.e. not the 2D
    bins that are fit, so shape effects in p_n are under-counted), against the null-fit
    chi2. The ratio is only indicative. Writes ``injection_size.csv`` and
    ``injection_size``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2, camp = f2_lib(), ctx.camp
    rows = []
    for route, stems in (("fd", PHYS + camp.tech), ("ds", camp.dials)):
        for s in stems:
            st = stat_chi2(route, "b", s)
            p = f2.pair(route, "b", s)
            if p and np.isfinite(st):
                rows.append(
                    {
                        "route": route,
                        "dataset": s,
                        "stat chi2 (projected)": st,
                        "chi2 null b": p[0]["chi2"],
                        "null/stat": p[0]["chi2"] / st if st > 0 else np.nan,
                    }
                )
    sz = pd.DataFrame(rows)
    if sz.empty:
        print("injection-size: no projected histograms found")
        return
    show(sz.sort_values("stat chi2 (projected)", ascending=False), width=220)
    ctx.save_table(sz, "injection_size.csv", index=False)
    ctx.head["stat_chi2_range"] = [
        float(sz["stat chi2 (projected)"].min()),
        float(sz["stat chi2 (projected)"].max()),
    ]
    fig, ax = plt.subplots(figsize=(7, 6))
    ax.scatter(
        sz["stat chi2 (projected)"], sz["chi2 null b"] + LOG_FLOOR,
        c=["C3" if r == "fd" else "C0" for r in sz["route"]], s=20,
    )  # fmt: skip
    lim = [LOG_FLOOR, 1e5]
    ax.plot(lim, lim, "k--", lw=0.8)
    ax.set_xscale("log")
    ax.set_yscale("log")
    for _, r in sz.sort_values("chi2 null b", ascending=False).head(9).iterrows():
        ax.annotate(
            r["dataset"], (r["stat chi2 (projected)"], r["chi2 null b"] + LOG_FLOOR),
            fontsize=7, xytext=(3, 3), textcoords="offset points",
        )  # fmt: skip
    ax.set_xlabel(r"stat-only $\chi^2$ of the injection (projected spectra)")
    ax.set_ylabel(r"null-fit $\chi^2$ (combined analysis)")
    fig.tight_layout()
    ctx.save_fig(fig, "injection_size")


def section_bounds(ctx: Context) -> None:
    """
    Nuisance parameters at their bounds.

    Several detector parameters have bounded (flat) priors on [-1, 1]. If the null fit
    pushes them to the bound, the remaining chi2 is limited by the prior envelope and not by
    the flexibility of the model; this lists them for every dataset (combined analysis,
    null fit; a parameter counts as pegged within 0.01 of +-1). Writes
    ``bounded_parameters.csv``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2, camp = f2_lib(), ctx.camp
    rows = []
    for route, stems in (("fd", PHYS + camp.tech + camp.pois), ("ds", camp.ds)):
        for s in stems:
            p = f2.pair(route, "b", s)
            if p:
                nm = f2.nuisance_names(p[0])
                peg = [n for n in nm if abs(abs(p[0]["values"][n]) - 1) < 0.01]
                rows.append(
                    {
                        "dataset": s,
                        "n at bound": len(peg),
                        "parameters": "; ".join(peg),
                        "chi2 null": p[0]["chi2"],
                    }
                )
    pg = pd.DataFrame(rows)
    if pg.empty:
        print("bounds: no fits found")
        return
    print(pg[pg["n at bound"] > 0].to_string(index=False))
    ctx.save_table(pg, "bounded_parameters.csv", index=False)
    ctx.head["n_datasets_with_bounded"] = int((pg["n at bound"] > 0).sum())
    ctx.head["n_datasets"] = int(len(pg))


