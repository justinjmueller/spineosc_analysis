def pull_overlay(
    route: str, stem: str, label: str, output: Path, fmt: str = "pdf", variant: str = "fix"
) -> dict | None:
    """
    Post-fit nuisance values of the analyses overlaid, for one dataset.

    Values are in prior sigma with the MCMC posterior width as the error bar.

    Parameters
    ----------
    route : str
        ``fd`` or ``ds``.
    stem : str
        Dataset stem.
    label : str
        Title text.
    output : Path
        Figure root; written to ``<output>/pulls/pulls_<variant>_<route>_<stem>.<fmt>``.
    fmt : str, optional
        File format.
    variant : str, optional
        ``fix`` (oscillation fixed) or ``free``.

    Returns
    -------
    dict or None
        The fits per analysis, or None if none is available.
    """
    f2 = f2_lib()
    cfgs, cc = f2.CONFIGS, f2.CFG_COLOR
    avail = [c for c in cfgs if f2.available(route, c, variant, stem)]
    if not avail:
        return None
    fits = {c: f2.read_fit(route, c, variant, stem) for c in avail}
    names = f2.nuisance_names(fits[avail[0]])
    x = np.arange(len(names))
    fig, ax = plt.subplots(figsize=(18, 5.2))
    ax.axhspan(-1, 1, color="0.9", zorder=0)
    ax.axhline(0, color="k", lw=0.8)
    for c, off in zip(avail, np.linspace(-0.22, 0.22, len(avail)), strict=True):
        y = np.array([fits[c]["values"].get(n, np.nan) for n in names])
        e = np.array([fits[c]["sigma"].get(n, np.nan) for n in names])
        ax.errorbar(
            x + off, y, yerr=e, fmt="o", ms=3, lw=0.9, color=cc[c],
            label=f"{cfgs[c]} ($\\chi^2$ = {fits[c]['chi2']:.1f})",
        )  # fmt: skip
    ax.set_xticks(x)
    ax.set_xticklabels(names, rotation=90, fontsize=6.5)
    ax.set_xlim(-1, len(names))
    ax.set_ylabel(r"post-fit value [prior $\sigma$]")
    state = "oscillation fixed" if variant == "fix" else "oscillation floating"
    ax.set_title(f"{label} ({state})", fontsize=12)
    ax.legend(loc="upper right", fontsize=9, ncol=3)
    common.save_figure(fig, output / "pulls" / f"pulls_{variant}_{route}_{stem}.{fmt}")
    return fits


def section_pulls(ctx: Context) -> None:
    """
    Pulls.

    Post-fit nuisance values (prior sigma) with the MCMC posterior width as error bar,
    overlaying the combined, single-proton, multi-proton and merged analyses, for each
    dataset and both fit variants (``pulls/``); and, for each dataset, the largest pull in
    each analysis (``max_pulls.csv``; nuisance-only fits).

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2 = f2_lib()
    todo = routed(ctx.camp)
    for route, stem in todo:
        for v in ("fix", "free"):
            pull_overlay(route, stem, stem.replace("_", " "), ctx.args.output, ctx.args.format, v)
    rows = []
    for route, stem in todo:
        r = {"route": route, "dataset": stem}
        for c in f2.CONFIGS:
            p = f2.pair(route, c, stem)
            if p:
                nm = f2.nuisance_names(p[0])
                j = max(nm, key=lambda n, p=p: abs(p[0]["values"][n]))
                r[f"max|pull| {c}"] = abs(p[0]["values"][j])
                r[f"param {c}"] = j
        rows.append(r)
    pl = pd.DataFrame(rows)
    ctx.save_table(pl, "max_pulls.csv", index=False)
    if "max|pull| b" in pl:
        show(pl.sort_values("max|pull| b", ascending=False).head(25), ".3g", width=250, rows=120)


