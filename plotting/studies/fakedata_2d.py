def section_false_signal(ctx: Context) -> None:
    """
    Where the oscillation fit lands for non-oscillation fake data.

    A non-oscillation mismodelling that the oscillation parameters partly absorb would
    appear as a preference for a sterile-like signal. For every non-oscillation dataset
    with Delta chi2 > 1 in any analysis: the fitted point and the nominal (Wilks, 2 dof,
    **not validated here**) Gaussian-equivalent two-sided significance. Writes
    ``false_oscillation_signal.csv``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2 = f2_lib()
    rows = []
    for route, stem in routed(ctx.camp):
        if stem.startswith(OSC_LIKE):
            continue
        for cfg in f2.CONFIGS:
            p = f2.pair(route, cfg, stem)
            if p and dchi2(p) > 1.0:
                d = dchi2(p)
                rows.append(
                    {
                        "dataset": stem,
                        "config": f2.CONFIGS[cfg],
                        "dchi2": d,
                        "fit dm2 [eV2]": p[1]["dm2"],
                        "fit sin2 2th": p[1]["s22"],
                        "nominal sigma (Wilks)": stats.norm.isf(f2.wilks_p(d) / 2),
                    }
                )
    fo = pd.DataFrame(rows)
    if fo.empty:
        print("false-signal: no dataset with Delta chi2 > 1")
        return
    show(fo.sort_values("dchi2", ascending=False), ".3g", width=220)
    ctx.save_table(fo, "false_oscillation_signal.csv", index=False)
    ctx.head["false_signal_b"] = (
        fo[fo.config == f2.CONFIGS["b"]]
        .sort_values("dchi2", ascending=False)
        .to_dict(orient="records")
    )


def seed_chi2(stem: str, seed: int, var: str) -> float:
    """
    Global best-fit chi2 of a seed-variation refit from its log.

    Parameters
    ----------
    stem : str
        Data-XML dataset stem (combined analysis).
    seed : int
        PROfit RNG seed of the refit.
    var : str
        ``fix`` or ``free``.

    Returns
    -------
    float
        The chi2, or nan if the log does not exist or has no chi2 line.
    """
    log = f2_lib().RUN / "logs" / f"global_d2b_{stem}_s{seed}_{var}.out"
    if not log.exists():
        return np.nan
    v = np.nan
    for line in log.read_text(errors="ignore").splitlines():
        if "Global Best Fit chi^2:" in line:
            v = float(line.split("chi^2:")[1].split()[0])
    return v


def section_seeds(ctx: Context) -> None:
    """
    Minimiser robustness: refits with different PROfit seeds.

    The same data-XML fake datasets (combined analysis) refit with two extra RNG seeds
    (``-s 7``, ``-s 13``); the default run is the reference. Repeating a run with the
    default seed reproduced the earlier chi2 exactly, so a re-run alone is not a robustness
    test. Writes ``seed_robustness.csv``.

    Parameters
    ----------
    ctx : Context
        Run context.
    """
    f2 = f2_lib()
    rows = []
    for stem in SEED_STEMS:
        p = f2.pair("ds", "b", stem)
        if not p:
            continue
        r = {
            "dataset": stem,
            "null (default seed)": p[0]["chi2"],
            "osc (default seed)": p[1]["chi2"],
        }
        for seed in SEEDS:
            r[f"null s{seed}"] = seed_chi2(stem, seed, "fix")
            r[f"osc s{seed}"] = seed_chi2(stem, seed, "free")
        vals_n = [r["null (default seed)"], *(r[f"null s{s}"] for s in SEEDS)]
        vals_o = [r["osc (default seed)"], *(r[f"osc s{s}"] for s in SEEDS)]
        r["max |dnull|"] = float(np.nanmax(np.abs(np.array(vals_n) - vals_n[0])))
        r["max |dosc|"] = float(np.nanmax(np.abs(np.array(vals_o) - vals_o[0])))
        rows.append(r)
    sr = pd.DataFrame(rows)
    if sr.empty:
        print("seeds: no data-XML combined fits found")
        return
    show(sr, ".5g")
