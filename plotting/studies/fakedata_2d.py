class Campaign(NamedTuple):
    """Fake-data datasets of the 2D campaign, from ``jobs_2d.txt``."""

    jobs: list[list[str]]
    ds: list[str]  #: data-XML datasets (including ``ctrl``)
    fd: list[str]  #: ``--use-fake-data`` stems
    pois: list[str]  #: Poisson throws among ``fd``
    tech: list[str]  #: technote-style QE-interference / spectral-function stems
    dials: list[str]  #: data-XML datasets without ``ctrl``


@dataclass
class Context:
    """Run-time state shared by the sections of one invocation."""

    args: argparse.Namespace
    camp: Campaign
    #: Numbers quoted in the report, merged into ``headline.json`` at the end of the run.
    head: dict = field(default_factory=dict)

    @property
    def tables(self) -> Path:
        """Directory of the CSV tables."""
        return self.args.output / "tables"

    def save_fig(self, fig: plt.Figure, name: str) -> Path:
        """Write a figure into the output directory in the chosen format."""
        return common.save_figure(fig, self.args.output / f"{name}.{self.args.format}")

    def save_table(self, df: pd.DataFrame, name: str, **kwargs) -> None:
        """Write a table as CSV into the tables directory."""
        self.tables.mkdir(parents=True, exist_ok=True)
        df.to_csv(self.tables / name, **kwargs)


@cache
def f2_lib() -> ModuleType:
    """
    Import the ``fd2d`` helper library from ``plotting/scripts``.

    Returns
    -------
    module
        ``fd2d`` (global-fit readers and tables; not modified or copied here).
    """
    if str(SCRIPTS) not in sys.path:
        sys.path.insert(0, str(SCRIPTS))
    import fd2d

    return fd2d


def load_campaign() -> Campaign:
    """
    Datasets of the campaign from its job list.

    Returns
    -------
    Campaign
        Job lines and the derived dataset lists.

    Raises
    ------
    SystemExit
        If ``jobs_2d.txt`` does not exist.
    """
    path = f2_lib().RUN / "jobs_2d.txt"
    if not path.exists():
        raise SystemExit(f"missing job list {path}")
    jobs = [line.split() for line in path.read_text().splitlines()]
    ds = list(dict.fromkeys(j[2] for j in jobs if j[0] == "ds"))
    fd = list(dict.fromkeys(j[3] for j in jobs if j[0] == "fd"))
    return Campaign(
        jobs=jobs,
        ds=ds,
        fd=fd,
        pois=[s for s in fd if s.startswith("pois")],
        tech=[s for s in fd if s.startswith(("qeint", "specf"))],
        dials=[s for s in ds if s != "ctrl"],
    )


def routed(camp: Campaign) -> list[tuple[str, str]]:
    """(route, stem) of every non-control dataset of interest: native + technote, then dials."""
    return [("fd", s) for s in PHYS + camp.tech] + [("ds", s) for s in camp.dials]


def dchi2(p: tuple[dict, dict]) -> float:
    """Delta chi2 of a (null, oscillation) pair of fits."""
    return p[0]["chi2"] - p[1]["chi2"]


def show(df: pd.DataFrame, fmt: str = ".4g", width: int = 250, rows: int = 100, **kw) -> None:
    """Print a table with the display options used throughout the study."""
    with pd.option_context(
        "display.width", width, "display.max_rows", rows, "display.float_format",
        lambda v: format(v, fmt),
    ):  # fmt: skip
        print(df.to_string(index=False, **kw))


