"""
Fake-data fits and the single-channel question: null vs oscillation fits per configuration.

Replaces ``plotting/fakedata_channel_studies.ipynb`` (generated by
``plotting/scripts/build_fakedata_channel_notebook.py``). It reads the global fits of
``runs/fakedata_full`` through the library ``plotting/scripts/fd_fits.py`` (imported,
not copied) and makes the tables and figures that extend the fake-data section of the
technote (``spineosc_technote/sections/fake_data_studies.tex``).

What the technote does: each fake dataset is fit twice, a **null fit** (nuisance
parameters only) and an **oscillation fit** (:math:`\\Delta m^2_{41}` and
:math:`\\sin^2 2\\theta_{\\mu\\mu}` also float); the test statistic is
:math:`\\Delta\\chi^2=\\chi^2_{\\rm null}-\\chi^2_{\\rm osc}` with Wilks p-values for two
degrees of freedom (to be replaced by Feldman-Cousins); post-fit nuisance pulls and
post-fit spectra are shown for both fits. Its studies are a Poisson fluctuation of the
CV, +-1 sigma shifts of the QE interference and spectral-function models, and the three
IceCube 2024 oscillation points. (Its numbers predate the v1.1.0 selection;
``xml/MANIFEST.toml`` notes those reruns are pending.)

Here the same two fits are run on every fake dataset made with the reBruce dials
(``spinefd``) and on PROfit's native IceCube injections, for **three analysis
configurations**: both channels (``b``), **single-proton only** (``1p``, ``ccqelike``)
and **multi-proton only** (``Np``, ``nproton``). The single-channel analyses are
separate XMLs (the other channel removed from the ``xml/systematics/systematics_suite.xml``
structure), processed and fit exactly like the two-channel one, with the **full
systematics suite** on the CV. Fake data is the CV MC reweighted by the dial at +1
sigma (``--use-fake-data --inject-systs``), or by PROfit's own oscillation injection, or
a Poisson throw of the CV; the injected dial is excluded from the fit. No real beam data
is used anywhere.

Inputs: ``runs/fakedata_full/jobs_fits.txt`` (the injection order of the queue) and the
fit outputs described in ``fd_fits.py`` (``fd<cfg>_g<free|fix>_<stem>_global_fit.txt``,
``..._PROglobal.root``, ``logs/global_...out``, ``done/`` markers). Fits that are not
available are skipped.

Sections (``--list-sections``; select with ``--section <name|number>``, repeatable;
default is all, in order):

====  ==============  ======================================================
 1    dchi2           Delta chi2 of every injection per configuration
 2    poisson         Poisson throws: the null distribution of Delta chi2
 3    constraints     how much does each channel constrain the systematics?
 4    detectability   which fake data can each analysis see? (heat maps)
 5    recovery        recovering the injected oscillation point
 6    pulls           nuisance pulls, overlays and single-channel pull bias
 7    summary         detectability and largest pull table (``summary.csv``)
====  ==============  ======================================================

Outputs go to ``plotting/fakedata_channel_figures`` (git-ignored; ``--output`` to change):
``poisson_null``, ``constraint_widths``, ``detectability_heatmap``, ``pull_bias_scatter``
(figure files in ``--format``), ``pulls/pulls_<fix|free>_<stem>``, and ``summary.csv``.

Usage (mutools environment)::

    /Users/mueller/Projects/mutools/.venv/bin/python plotting/studies/fakedata_channel.py \\
        --section dchi2 --section poisson
"""

