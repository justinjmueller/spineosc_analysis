def section_dchi2(args: argparse.Namespace) -> None:
    """
    Delta chi2 of every injection, per analysis configuration.

    :math:`\\Delta\\chi^2=\\chi^2_{\\rm null}-\\chi^2_{\\rm osc}` and its Wilks p-value (2
    dof), as in the technote tables; the oscillation fit also reports the fitted point.
    Then a cross-check against the technote's IceCube numbers (26.85, 21.57, 33.14; older
    selection, different production): ours, for PROfit's native injection, per
    configuration. The floating fit recovers the injected point exactly in every
    configuration where it is sensitive.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    fd = fd_lib()
    stems = load_stems()
    with pd.option_context(
        "display.width", 220, "display.max_rows", 200, "display.float_format", lambda v: f"{v:.4g}"
    ):
        for c in fd.CONFIGS:
            print(f"=== {fd.CONFIGS[c]} ===")
            print(dchi2_table(c, stems.injections).to_string(index=False))
            print()
    rows = []
    for s, t in TECHNOTE_DCHI2.items():
        r = {"point": label(s), "technote": t}
        for c in fd.CONFIGS:
            r[fd.CONFIGS[c]] = fd.delta_chi2(c, s)
        rows.append(r)
    print(pd.DataFrame(rows).round(2).to_string(index=False))


def section_poisson(args: argparse.Namespace) -> None:
    """
    Poisson fluctuations: the null distribution of Delta chi2.

    Ten Poisson throws of the CV per configuration. If Wilks' theorem held,
    :math:`\\Delta\\chi^2` would follow a :math:`\\chi^2` distribution with 2 degrees of
    freedom (CDF dotted). Ten throws only give a coarse check, enough to see whether the
    Wilks p-values in the technote are reasonable and what the single-channel analyses
    do to the distribution. Writes ``poisson_null`` (cumulative Delta chi2 and the
    null-fit chi2 histogram) and prints a KS table.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    fd = fd_lib()
    pois = load_stems().poisson
    fig, axes = plt.subplots(1, 2, figsize=(14, 4.6))
    rows = []
    for c in fd.CONFIGS:
        d = np.array([fd.delta_chi2(c, s) for s in pois])
        d = d[np.isfinite(d)]
        n0 = np.array([fd.read_fit(c, "fix", s)["chi2"] for s in pois if fd.available(c, "fix", s)])
        if len(d) == 0:
            continue
        xs = np.sort(d)
        axes[0].step(
            xs, np.arange(1, len(xs) + 1) / len(xs), where="post", color=CFG_COLOR[c],
            label=f"{fd.CONFIGS[c]} (n = {len(xs)})",
        )  # fmt: skip
        ks = stats.kstest(d, stats.chi2(2).cdf)
        rows.append(
            {
                "config": fd.CONFIGS[c],
                "throws": len(d),
                "mean dchi2": d.mean(),
                "max dchi2": d.max(),
                "mean chi2 null": n0.mean(),
                "KS p vs chi2(2)": ks.pvalue,
            }
        )
        axes[1].hist(
            n0, bins=NULL_BINS, histtype="step", color=CFG_COLOR[c], label=fd.CONFIGS[c]
        )
    xx = np.linspace(0, 12, 200)
    axes[0].plot(xx, stats.chi2(2).cdf(xx), "k:", label=r"$\chi^2$, 2 dof")
    axes[0].set_xlabel(r"$\Delta\chi^2=\chi^2_{\rm null}-\chi^2_{\rm osc}$")
    axes[0].set_ylabel("cumulative fraction")
    axes[0].legend(fontsize=9)
    axes[1].set_xlabel(r"null-fit $\chi^2$")
    axes[1].set_ylabel("throws")
    axes[1].legend(fontsize=9)
    fig.tight_layout()
    common.save_figure(fig, args.output / f"poisson_null.{args.format}")
    print(pd.DataFrame(rows).round(3).to_string(index=False))


def section_constraints(args: argparse.Namespace) -> None:
    """
    How much does each channel constrain the systematics?

    With the CV as fake data (no pulls expected), the width of each nuisance parameter's
    posterior measures how well the data constrain it; a width of 1 is the prior. Uses the
    nuisance-only fit of the three configurations; prints the number of parameters
    constrained below 0.5 and 0.8 sigma and the 25 most constrained, and writes
    ``constraint_widths`` (single- vs multi-proton scatter and the sorted widths).

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    fd = fd_lib()
    cfg = fd.CONFIGS
    w = pd.DataFrame({c: nuisance_widths(c) for c in cfg if fd.available(c, "fix", "ctrl")})
    print("nuisance parameters:", len(w))
    have = [c for c in ("b", "1p", "Np") if c in w]
    for c in have:
        print(
            f"  {cfg.get(c, c):20s} constrained below 0.5 sigma: {(w[c] < 0.5).sum():3d}"
            f"   below 0.8 sigma: {(w[c] < 0.8).sum():3d}   median width {w[c].median():.2f}"
        )
    ref = "b" if "b" in w else w.columns[0]
    top = w.sort_values(ref).head(25)
    with pd.option_context("display.width", 200, "display.float_format", lambda v: f"{v:.2f}"):
        print("\nMost constrained parameters (posterior width, prior = 1):")
        print(top[have].rename(columns=cfg).to_string())
    if not {"1p", "Np"} <= set(w.columns):
        print("constraints: single-channel controls missing, no figure")
        return
    fig, axes = plt.subplots(1, 2, figsize=(14, 5.4))
    ax = axes[0]
    ax.scatter(w["1p"], w["Np"], s=14, color="C2")
    ax.plot([0, 1.2], [0, 1.2], "k--", lw=0.8)
    for n in w.assign(d=(w["1p"] - w["Np"]).abs()).sort_values("d").tail(7).index:
        ax.annotate(
            n, (w.loc[n, "1p"], w.loc[n, "Np"]), fontsize=7, xytext=(3, 3),
            textcoords="offset points",
        )  # fmt: skip
    ax.set_xlabel("posterior width, single-proton only")
    ax.set_ylabel("posterior width, multi-proton only")
    ax.set_title("Nuisance constraints: one channel vs the other")
    ax = axes[1]
    order = w[ref].sort_values().index
    x = np.arange(len(order))
    for c in have:
        ax.plot(x, w.loc[order, c].values, ".", color=CFG_COLOR[c], label=cfg[c], ms=5)
    ax.axhline(1, color="0.5", ls="--", lw=0.8)
    ax.set_xlabel("nuisance parameter, sorted by two-channel constraint")
    ax.set_ylabel("posterior width [prior sigma]")
    ax.legend(fontsize=9)
    fig.tight_layout()
    common.save_figure(fig, args.output / f"constraint_widths.{args.format}")


def detectability_matrix(kind: str, stems: list[str]) -> np.ndarray:
    """
    Null-fit chi2 or Delta chi2 for every injection and configuration.

    Parameters
    ----------
    kind : str
        ``chi2null`` or ``dchi2``.
    stems : list of str
        Injection stems (rows).

    Returns
    -------
    np.ndarray
        Array of shape (len(stems), n configurations); nan where a fit is missing.
    """
    fd = fd_lib()
    m = np.full((len(stems), len(fd.CONFIGS)), np.nan)
    for i, s in enumerate(stems):
        for j, c in enumerate(fd.CONFIGS):
            if kind == "dchi2":
                m[i, j] = fd.delta_chi2(c, s)
            elif fd.available(c, "fix", s):
                m[i, j] = fd.read_fit(c, "fix", s)["chi2"]
    return m


def section_detectability(args: argparse.Namespace) -> None:
    """
    Which fake data can each analysis see?

    The null-fit chi2 (the fake data against the best nuisance-only fit) and Delta chi2
    (the extra the oscillation fit buys) for every injection and configuration; larger
    means more detectable. Writes ``detectability_heatmap`` (log colour scale, values
    annotated).

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    fd = fd_lib()
    inj = load_stems().injections
    fig, axes = plt.subplots(1, 2, figsize=(14, max(6, 0.3 * len(inj))), sharey=True)
    titles = (r"null-fit $\chi^2$", r"$\Delta\chi^2$ (null $-$ oscillation fit)")
    for ax, kind, title in zip(axes, ("chi2null", "dchi2"), titles, strict=True):
        m = detectability_matrix(kind, inj)
        logm = np.log10(np.clip(m, 1e-3, None))
        ax.imshow(logm, aspect="auto", cmap="viridis", vmin=-2, vmax=2.5)
        for i in range(m.shape[0]):
            for j in range(m.shape[1]):
                if np.isfinite(m[i, j]):
                    ax.text(
                        j, i, f"{m[i, j]:.2g}", ha="center", va="center", fontsize=7,
                        color="w" if np.log10(max(m[i, j], 1e-3)) < 1 else "k",
                    )  # fmt: skip
        ax.set_xticks(range(3))
        ax.set_xticklabels([fd.CONFIGS[c] for c in fd.CONFIGS], rotation=20, ha="right", fontsize=9)
        ax.set_title(title)
    axes[0].set_yticks(range(len(inj)))
    axes[0].set_yticklabels([label(s) for s in inj], fontsize=7)
    fig.tight_layout()
    common.save_figure(fig, args.output / f"detectability_heatmap.{args.format}")


def section_recovery(args: argparse.Namespace) -> None:
    """
    Recovering the injected oscillation point.

    For the native IceCube injections the oscillation fit should return the injected
    (dm2, sin^2 2theta_mumu) with chi2 close to 0. The same three points injected
    through the reBruce dial with a fixed 110 m baseline, and with the event's own
    baseline, show how much the baseline treatment matters. Prints the table.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    fd = fd_lib()
    rows = []
    for s, (dm2, s22) in INJECTED_POINTS.items():
        for c in fd.CONFIGS:
            if fd.available(c, "free", s) and fd.available(c, "fix", s):
                o = fd.read_fit(c, "free", s)
                rows.append(
                    {
                        "injection": label(s),
                        "config": fd.CONFIGS[c],
                        "injected dm2": dm2,
                        "fit dm2": o["dm2"],
                        "injected s22": s22,
                        "fit s22": o["s22"],
                        "chi2 osc": o["chi2"],
                        "dchi2": fd.delta_chi2(c, s),
                    }
                )
    print(pd.DataFrame(rows).round(3).to_string(index=False))


def pull_overlay(
    stem: str, output: Path, fmt: str = "pdf", variant: str = "fix", ntop: int = 2
) -> dict[str, dict] | None:
    """
    Post-fit nuisance values of the three configurations overlaid, for one injection.

    Values are in units of the prior sigma (error bars: MCMC posterior width). Where the
    two single-channel analyses disagree on a pull, the fake data would bias that
    systematic differently depending on which channel is used. The ``ntop`` largest pulls
    of each configuration are labelled.

    Parameters
    ----------
    stem : str
        Injection stem.
    output : Path
        Figure root; written to ``<output>/pulls/pulls_<variant>_<stem>.<fmt>``.
    fmt : str, optional
        File format.
    variant : str, optional
        ``fix`` (oscillation fixed) or ``free``.
    ntop : int, optional
        Number of labelled pulls per configuration.

    Returns
    -------
    dict or None
        The fits per configuration, or None if no configuration has this fit.
    """
    fd = fd_lib()
    avail = [c for c in fd.CONFIGS if fd.available(c, variant, stem)]
    if not avail:
        return None
    fits = {c: fd.read_fit(c, variant, stem) for c in avail}
    names = fd.nuisance_names(fits[avail[0]])
    x = np.arange(len(names))
    fig, ax = plt.subplots(figsize=(18, 5.2))
    ax.axhspan(-1, 1, color="0.9", zorder=0)
    ax.axhline(0, color="k", lw=0.8)
    for c, off in zip(avail, np.linspace(-0.22, 0.22, len(avail)), strict=True):
        y = np.array([fits[c]["values"].get(n, np.nan) for n in names])
        e = np.array([fits[c]["sigma"].get(n, np.nan) for n in names])
        ax.errorbar(
            x + off, y, yerr=e, fmt="o", ms=3, lw=0.9, color=CFG_COLOR[c],
            label=f"{fd.CONFIGS[c]} ($\\chi^2$ = {fits[c]['chi2']:.1f})",
        )  # fmt: skip
    for c in avail:
        yy = np.array([fits[c]["values"].get(n, 0.0) for n in names])
        for i in np.argsort(-np.abs(yy))[:ntop]:
            ax.annotate(
                names[i], (x[i], yy[i]), xytext=(0, 7 if yy[i] >= 0 else -12),
                textcoords="offset points", ha="center", fontsize=7,
            )  # fmt: skip
    ax.set_xticks(x)
    ax.set_xticklabels(names, rotation=90, fontsize=6.5)
    ax.set_xlim(-1, len(names))
    ax.set_ylabel(r"post-fit value [prior $\sigma$]")
    state = "oscillation fixed" if variant == "fix" else "oscillation floating"
    ax.set_title(f"{label(stem)}  ({state})", fontsize=12)
    ax.legend(loc="upper right", fontsize=9, ncol=3)
    common.save_figure(fig, output / "pulls" / f"pulls_{variant}_{stem}.{fmt}")
    return fits


def pull_pair(stem: str, variant: str = "fix") -> pd.DataFrame | None:
    """
    Single-proton vs multi-proton pulls of one injection.

    Parameters
    ----------
    stem : str
        Injection stem.
    variant : str, optional
        ``fix`` or ``free``.

    Returns
    -------
    pandas.DataFrame or None
        Columns ``1p``, ``Np`` (pulls), ``s1p``, ``sNp`` (posterior widths) and ``diff``
        (pull difference in units of the quadrature sum of the widths); None if either
        configuration is missing.
    """
    fd = fd_lib()
    if not (fd.available("1p", variant, stem) and fd.available("Np", variant, stem)):
        return None
    a, b = fd.read_fit("1p", variant, stem), fd.read_fit("Np", variant, stem)
    names = fd.nuisance_names(a)
    df = pd.DataFrame(
        {
            "1p": [a["values"].get(n, np.nan) for n in names],
            "Np": [b["values"].get(n, np.nan) for n in names],
            "s1p": [a["sigma"].get(n, np.nan) for n in names],
            "sNp": [b["sigma"].get(n, np.nan) for n in names],
        },
        index=names,
    )
    df["diff"] = (df["1p"] - df["Np"]) / np.hypot(df["s1p"], df["sNp"])
    return df


def section_pulls(args: argparse.Namespace) -> None:
    """
    Pulls: what the fit does to the nuisance parameters.

    Writes the three-configuration overlay for every injection and both fit variants
    (``pulls/``). Then the single-channel pull bias: for each injection the post-fit pull
    of every nuisance parameter in the single-proton analysis against the multi-proton
    one (nuisance-only fits). Points off the diagonal are systematics whose best-fit value
    depends on which channel is used; the printed table lists the largest differences in
    units of the quadrature sum of the posterior widths. Writes ``pull_bias_scatter``.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    stems = load_stems()
    for s in stems.injections:
        for v in ("fix", "free"):
            pull_overlay(s, args.output, args.format, variant=v)
    print("pull overlays written to", args.output / "pulls")

    sel = [s for s in PULL_BIAS_STEMS if pull_pair(s) is not None]
    if sel:
        fig, axes = plt.subplots(2, 4, figsize=(18, 8.5))
        for ax, s in zip(axes.ravel(), sel, strict=False):
            df = pull_pair(s)
            ax.scatter(df["1p"], df["Np"], s=14, color="C4", alpha=0.8)
            lim = max(1.2, np.nanmax(np.abs(df[["1p", "Np"]].values)) * 1.1)
            ax.plot([-lim, lim], [-lim, lim], "k--", lw=0.8)
            for n in df["diff"].abs().sort_values().tail(3).index:
                ax.annotate(
                    n, (df.loc[n, "1p"], df.loc[n, "Np"]), fontsize=9, xytext=(4, 4),
                    textcoords="offset points",
                )  # fmt: skip
            ax.set_xlabel("pull, single-proton only")
            ax.set_ylabel("pull, multi-proton only")
            ax.set_title(label(s), fontsize=11)
        fig.tight_layout()
        common.save_figure(fig, args.output / f"pull_bias_scatter.{args.format}")
    rows = []
    for s in stems.injections:
        df = pull_pair(s)
        if df is None:
            continue
        j = df["diff"].abs().idxmax()
        rows.append(
            {
                "injection": s,
                "max |1p-Np| [sigma]": abs(df.loc[j, "diff"]),
                "parameter": j,
                "pull 1p": df.loc[j, "1p"],
                "pull Np": df.loc[j, "Np"],
                "max|pull| 1p": np.nanmax(np.abs(df["1p"])),
                "max|pull| Np": np.nanmax(np.abs(df["Np"])),
            }
        )
    if not rows:
        print("pulls: no single-channel pairs available")
        return
    tab = pd.DataFrame(rows)
    with pd.option_context(
        "display.width", 220, "display.max_rows", 100, "display.float_format", lambda v: f"{v:.3g}"
    ):
        print(tab.sort_values("max |1p-Np| [sigma]", ascending=False).to_string(index=False))


def section_summary(args: argparse.Namespace) -> None:
    """
    Summary: detectability and the largest post-fit pull per configuration.

    For each injection and configuration: the nuisance-only chi2, Delta chi2 and the
    largest post-fit pull. Prints the table and writes ``summary.csv``.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    fd = fd_lib()
    rows = []
    for s in load_stems().injections:
        r: dict[str, object] = {"injection": s}
        for c in fd.CONFIGS:
            if fd.available(c, "fix", s) and fd.available(c, "free", s):
                f = fd.read_fit(c, "fix", s)
                r[f"chi2 null {c}"] = f["chi2"]
                r[f"dchi2 {c}"] = fd.delta_chi2(c, s)
                r[f"max|pull| {c}"] = max(abs(f["values"][n]) for n in fd.nuisance_names(f))
        rows.append(r)
    summary = pd.DataFrame(rows)
    args.output.mkdir(parents=True, exist_ok=True)
    summary.to_csv(args.output / "summary.csv", index=False)
    with pd.option_context(
        "display.width", 250, "display.max_rows", 100, "display.float_format", lambda v: f"{v:.3g}"
    ):
        print(summary.to_string(index=False))


class Section(NamedTuple):
    """One selectable section of the study."""

    number: int
    name: str
    func: Callable[[argparse.Namespace], None]
    title: str


#: All sections in order.
SECTIONS = [
    Section(1, "dchi2", section_dchi2, "Delta chi2 of every injection per configuration"),
    Section(2, "poisson", section_poisson, "Poisson throws: null distribution of Delta chi2"),
    Section(3, "constraints", section_constraints, "nuisance constraints per channel"),
    Section(4, "detectability", section_detectability, "detectability heat maps"),
    Section(5, "recovery", section_recovery, "recovering the injected oscillation point"),
    Section(6, "pulls", section_pulls, "pull overlays and single-channel pull bias"),
    Section(7, "summary", section_summary, "summary table (summary.csv)"),
]


def resolve_sections(requested: list[str] | None) -> list[Section]:
    """
    Map ``--section`` values (names or numbers) to sections.

    Parameters
    ----------
    requested : list of str or None
        Values given on the command line; None selects every section.

    Returns
    -------
    list of Section
        The selected sections, in the order requested.

    Raises
    ------
    SystemExit
        If a value matches no section.
    """
    if not requested:
        return list(SECTIONS)
    out = []
    for item in requested:
        match = [s for s in SECTIONS if item == s.name or item == str(s.number)]
        if not match:
            raise SystemExit(f"unknown section {item!r}; use --list-sections")
        out.append(match[0])
    return out


def build_parser() -> argparse.ArgumentParser:
    """
    Command-line parser.

    Returns
    -------
    argparse.ArgumentParser
        Parser with the common study options plus ``--section`` and ``--list-sections``.
    """
    parser = common.base_parser(__doc__)
    parser.set_defaults(output=OUTPUT)
    parser.add_argument("--section", action="append", help="section name or number (repeatable)")
    parser.add_argument("--list-sections", action="store_true", help="list sections and exit")
    return parser


def main(argv: list[str] | None = None) -> None:
    """
    Run the selected sections.

    Parameters
    ----------
    argv : list of str, optional
        Command-line arguments; defaults to ``sys.argv[1:]``.
    """
    args = build_parser().parse_args(argv)
    if args.list_sections:
        for s in SECTIONS:
            print(f"{s.number:2d}  {s.name:14s} {s.title}")
        return
    sections = resolve_sections(args.section)
    common.configure_style(args.format)
    stems = load_stems()
    fd = fd_lib()
    done = {
        c: sum(fd.available(c, v, s) for s in stems.all for v in ("free", "fix"))
        for c in fd.CONFIGS
    }
    print(f"completed fits per configuration (of {2 * len(stems.all)} each): {done}")
    for s in sections:
        print(f"== {s.number} {s.name}: {s.title}", file=sys.stderr)
        s.func(args)


if __name__ == "__main__":
    main()
