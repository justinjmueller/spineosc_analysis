class Stems(NamedTuple):
    """Injection stems in the order of the job queue."""

    all: list[str]
    poisson: list[str]
    injections: list[str]


@cache
def fd_lib() -> ModuleType:
    """
    Import the ``fd_fits`` helper library from ``plotting/scripts``.

    Returns
    -------
    module
        ``fd_fits`` (global-fit readers; not modified or copied here).
    """
    if str(SCRIPTS) not in sys.path:
        sys.path.insert(0, str(SCRIPTS))
    import fd_fits

    return fd_fits


def label(stem: str) -> str:
    """Display label of an injection stem (underscores replaced if unlabelled)."""
    return LABELS.get(stem, stem.replace("_", " "))


def load_stems() -> Stems:
    """
    Injection stems from the job queue ``jobs_fits.txt``.

    Returns
    -------
    Stems
        All stems (queue order, deduplicated), the Poisson throws and the others.

    Raises
    ------
    SystemExit
        If the job file does not exist.
    """
    jobs = fd_lib().RUN / "jobs_fits.txt"
    if not jobs.exists():
        raise SystemExit(f"missing job queue {jobs}")
    stems = list(dict.fromkeys(line.split()[2] for line in jobs.read_text().splitlines()))
    return Stems(
        stems,
        [s for s in stems if s.startswith("pois")],
        [s for s in stems if not s.startswith("pois")],
    )


def nuisance_widths(cfg: str, stem: str = "ctrl", variant: str = "fix") -> pd.Series:
    """
    MCMC posterior width of every nuisance parameter in one fit.

    Parameters
    ----------
    cfg : str
        Configuration key (``b``, ``1p``, ``Np``).
    stem : str, optional
        Injection stem; the default CV control has no pulls expected.
    variant : str, optional
        ``fix`` (nuisance-only fit) or ``free``.

    Returns
    -------
    pandas.Series
        Posterior width (prior = 1) indexed by parameter name.
    """
    fd = fd_lib()
    f = fd.read_fit(cfg, variant, stem)
    return pd.Series({n: f["sigma"].get(n, np.nan) for n in fd.nuisance_names(f)})


def dchi2_table(cfg: str, stems: list[str]) -> pd.DataFrame:
    """
    Null/oscillation chi2, Delta chi2, Wilks p-value and fitted point per injection.

    Parameters
    ----------
    cfg : str
        Configuration key.
    stems : list of str
        Injection stems; those missing either fit are skipped.

    Returns
    -------
    pandas.DataFrame
        One row per available injection.
    """
    fd = fd_lib()
    rows = []
    for s in stems:
        if not (fd.available(cfg, "free", s) and fd.available(cfg, "fix", s)):
            continue
        n, o = fd.read_fit(cfg, "fix", s), fd.read_fit(cfg, "free", s)
        d = n["chi2"] - o["chi2"]
        rows.append(
            {
                "injection": s,
                "chi2 null": n["chi2"],
                "chi2 osc": o["chi2"],
                "dchi2": d,
                "p (Wilks, 2 dof)": stats.chi2.sf(max(d, 0), 2),
                "fit dm2 [eV2]": o["dm2"],
                "fit sin2 2th": o["s22"],
            }
        )
    return pd.DataFrame(rows)


