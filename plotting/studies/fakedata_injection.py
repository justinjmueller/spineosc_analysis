def make_config(
    input_file: Path,
    output: str | None,
    xlim: list[float],
    ylim: list[float] | None,
    channel: int,
    detector: int,
    legend_loc: str,
    variable: int = 0,
) -> str:
    """
    TOML configuration for one mutools ``histogram`` panel.

    Parameters
    ----------
    input_file : Path
        PROfit plot file.
    output : str or None
        Output path; None disables saving (the figure is returned by pyplot).
    xlim, ylim : list of float
        Axis ranges; ``ylim`` None leaves the y range automatic.
    channel, detector : int
        Channel and detector indices.
    legend_loc : str
        Matplotlib legend location.
    variable : int, optional
        Variable index.

    Returns
    -------
    str
        TOML text for ``mutools.plotting.run``.
    """
    ylim_line = f"ylim = {list(ylim)}" if ylim is not None else ""
    # TOML literal strings: a python list repr would double the backslashes of the mathtext labels
    subchannels = "[" + ", ".join(f"'{s}'" for s in SUBCHANNELS) + "]"
    return rf"""
[general]
input = '{input_file}'
output = '{output if output is not None else ""}'
savefig = {str(output is not None).lower()}
code_version = '{common.CODE_VERSION}'
selection_version = '{common.SELECTION_VERSION}'
subchannels = {subchannels}
channels = ['Single-Proton', 'Multi-Proton']
detectors = {DETECTORS}

[[plot]]
type = 'histogram'
variable = {variable}
channel = {channel}
detectors = [{detector}]
colors = {COLORS}
xlabel = '{XLABEL}'
ylabel = '{YLABEL}'
xlim = {xlim}
{ylim_line}
rlim = {RLIM}
ratio = 'data'
watermark = '{common.WATERMARK}'
right_watermark = '{POT[detector]}'
disable_systematics = false
band_label = "Total Uncertainty"
show_chi2 = true
chi2_label = '{CHI2_LABEL}'
legend_ncol = 2
legend_loc = '{legend_loc}'
"""


def content_tops(
    input_file: Path, channel: int, detector: int, variable: int = 0
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Bin edges and the highest content (CV, CV + band, data + error) of each bin.

    Parameters
    ----------
    input_file : Path
        PROfit plot file.
    channel, detector : int
        Channel and detector indices.
    variable : int, optional
        Variable index.

    Returns
    -------
    low, high, top : np.ndarray
        Bin low/high edges and the largest of the three contents per bin.
    """
    from mutools.plotting.profit import ProfitPlotData, TraceType

    d = ProfitPlotData(input_file)
    key = f"{variable}:0:{detector}:{channel}:total"
    cv = d.get_trace(f"{key}:CV", TraceType.HIST_CONTENTS)
    band = d.get_trace(f"{key}:CV", TraceType.HIST_ERROR_BAND)
    dat = d.get_trace(f"{key}:DATA", TraceType.HIST_CONTENTS)
    derr = dat[:, 4] if dat.shape[1] > 4 else np.sqrt(np.maximum(dat[:, 3], 0.0))
    top = np.nanmax(np.vstack([cv[:, 3], band[:, 1] + band[:, 3], dat[:, 3] + derr]), axis=0)
    return cv[:, 1], cv[:, 2], top


def nice_ceil(x: float) -> float:
    """Round ``x`` up to two significant figures."""
    e = 10 ** math.floor(math.log10(x))
    return float(f"{math.ceil(round(x / e * 10, 6)) / 10 * e:.2g}")


def padded_ylim(
    input_file: Path,
    xlim: list[float],
    channel: int,
    detector: int,
    locs: tuple[str, ...] = ("upper right", "upper left"),
    margin: float = 0.95,
    max_iter: int = 6,
) -> tuple[list[float], str]:
    """
    Smallest y maximum (2 s.f.) at which no content reaches into the legend.

    The same procedure as ``datamc.ipynb``: the panel is drawn repeatedly, the legend
    box is measured, and ``ymax`` is raised until the bins under the legend fit below it.

    Parameters
    ----------
    input_file : Path
        PROfit plot file.
    xlim : list of float
        x range.
    channel, detector : int
        Channel and detector indices.
    locs : tuple of str, optional
        Legend corners tried.
    margin : float, optional
        Fraction of the legend's lower edge the content may reach.
    max_iter : int, optional
        Iterations per corner.

    Returns
    -------
    ylim : list of float
        ``[0, ymax]``.
    loc : str
        The legend corner that gives the smallest ``ymax``.

    Raises
    ------
    RuntimeError
        If the y limit does not converge.
    """
    from mutools.plotting import run

    lo, hi, top = content_tops(input_file, channel, detector)
    inx = (hi > xlim[0]) & (lo < xlim[1])
    floor = nice_ceil(1.1 * top[inx].max())
    best: tuple[float, str] | None = None
    for loc in locs:
        ymax = floor
        for _ in range(max_iter):
            plt.close("all")
            run(make_config(input_file, None, xlim, [0.0, ymax], channel, detector, loc))
            fig = plt.gcf()
            ax = fig.axes[0]
            fig.canvas.draw()
            box = ax.get_legend().get_window_extent().transformed(ax.transAxes.inverted())
            x0, x1 = ax.transData.inverted().transform(
                ax.transAxes.transform([[box.x0, 0], [box.x1, 0]])
            )[:, 0]
            under = inx & (hi > x0) & (lo < x1)
            plt.close("all")
            needed = nice_ceil(top[under].max() / (margin * box.y0)) if under.any() else floor
            if needed <= ymax:
                break
            ymax = needed
        else:
            raise RuntimeError(f"ylim did not converge: ch{channel} det{detector} {loc}")
        if best is None or ymax < best[0]:
            best = (ymax, loc)
    return [0.0, best[0]], best[1]


def render(stem: str, channel: int, detector: int, output: Path, fmt: str = "pdf") -> Path:
    """
    One panel: stacked CV with the full-systematics band, fake data and fake/CV ratio.

    Parameters
    ----------
    stem : str
        Key of `INJECTIONS`.
    channel, detector : int
        Channel and detector indices.
    output : Path
        Figure root directory; the panel goes to ``<output>/<stem>/``.
    fmt : str, optional
        File format.

    Returns
    -------
    Path
        The file written.
    """
    from mutools.plotting import run

    path = histogram_file(stem)
    xlim = XLIM[channel]
    ylim, loc = padded_ylim(path, xlim, channel, detector)
    plt.close("all")
    run(make_config(path, None, xlim, ylim, channel, detector, loc))
    fig = plt.gcf()
    ax = fig.axes[0]
    # mutools hard-codes the legend entry "Data"; this is MC reweighted by a dial
    for t in ax.get_legend().get_texts():
        if t.get_text() == "Data":
            t.set_text("Fake data")
    ax.text(
        0.5, 1.02, INJECTIONS[stem][1], transform=ax.transAxes, fontsize=10, ha="center",
        va="bottom",
    )  # fmt: skip
    name = f"fakedata_{stem}_{DETECTOR_TOKENS[detector]}_{CHANNEL_TOKENS[channel]}.{fmt}"
    target = common.save_figure(fig, output / stem / name)
    plt.close("all")
    return target


