def histogram_file(stem: str) -> Path:
    """
    Path of the PROfit ``plot`` histogram file of one injection.

    Parameters
    ----------
    stem : str
        Key of `INJECTIONS`.

    Returns
    -------
    Path
        ``runs/fakedata_full/<tag>_<stem>_PROplot_histograms.root``; the ``pl_*``
        dials use the ``fdb`` tag.
    """
    if stem.startswith("pl_"):
        return RUNDIR / f"{PL_TAG}_{stem}_PROplot_histograms.root"
    return RUNDIR / f"{TAG}_{stem}_PROplot_histograms.root"


def inject_args(stem: str) -> list[str]:
    """
    PROfit options that turn ``stem`` into the fake dataset.

    Parameters
    ----------
    stem : str
        Key of `INJECTIONS`.

    Returns
    -------
    list of str
        ``--inject-systs`` for dial injections, ``--inject`` for native physics
        injections, nothing for the closure ``ctrl``.
    """
    dial, _ = INJECTIONS[stem]
    args: list[str] = []
    if dial:
        args += ["--inject-systs", f"multisigma_{dial}", "1"]
    if stem in PHYSICS:
        args += ["--inject", "dmsq", str(PHYSICS[stem][0]), "sinsq2thmm", str(PHYSICS[stem][1])]
    return args


def profit(cmd_name: str, out_tag: str, stem: str, extra: tuple[str, ...] | list[str] = ()) -> None:
    """
    One PROfit call on the fake dataset ``stem``.

    The dial splines are excluded from the fit and uncertainty and nothing real is read.

    Parameters
    ----------
    cmd_name : str
        PROfit command (``plot`` or ``global``).
    out_tag : str
        Output tag (``-o``).
    stem : str
        Key of `INJECTIONS`.
    extra : sequence of str, optional
        Additional PROfit options (e.g. ``--syst-only``).

    Raises
    ------
    subprocess.CalledProcessError
        If PROfit fails.
    """
    cmd = [
        str(PROFIT), "--config", "fakedata_full.ini", "-o", out_tag, "--use-fake-data",
        "--scale-by-width", "--exclude-systs", *DIAL_NAMES, *extra, *inject_args(stem),
        "-l", f"logs/{cmd_name}_{out_tag}.log", cmd_name,
    ]  # fmt: skip
    subprocess.run(
        cmd, cwd=RUNDIR, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL
    )


def ensure_plot(stem: str, run_profit: bool) -> Path:
    """
    Run the PROfit ``plot`` step for one injection if its histogram file is missing.

    Parameters
    ----------
    stem : str
        Key of `INJECTIONS`.
    run_profit : bool
        Allow running PROfit; if False a missing file is left missing.

    Returns
    -------
    Path
        The histogram file (which may not exist).
    """
    path = histogram_file(stem)
    if not path.exists() and run_profit:
        profit("plot", stem, stem)
    return path


def global_tag(variant: str, stem: str) -> str:
    """Output tag of one global fit: ``g<variant>_<stem>``."""
    return f"g{variant}_{stem}"


def global_fit_file(variant: str, stem: str) -> Path:
    """Path of the best-fit vector of one global fit."""
    return RUNDIR / f"{TAG}_{global_tag(variant, stem)}_global_fit.txt"


def ensure_global(variant: str, stem: str, run_profit: bool) -> Path:
    """
    Run the PROfit ``global`` fit for one injection and variant if its output is missing.

    Parameters
    ----------
    variant : str
        Key of `VARIANTS`.
    stem : str
        Key of `INJECTIONS`.
    run_profit : bool
        Allow running PROfit.

    Returns
    -------
    Path
        The best-fit vector file (which may not exist).
    """
    out = global_fit_file(variant, stem)
    if not out.exists() and run_profit:
        profit("global", global_tag(variant, stem), stem, VARIANTS[variant][3])
    return out


