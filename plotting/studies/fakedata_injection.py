def selected_stems(args: argparse.Namespace) -> list[str]:
    """
    Injection stems chosen with ``--injection`` (all of `INJECTIONS` by default).

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.

    Returns
    -------
    list of str
        Stems, in `INJECTIONS` order.

    Raises
    ------
    SystemExit
        If a requested stem is unknown.
    """
    if not args.injection:
        return list(INJECTIONS)
    unknown = [s for s in args.injection if s not in INJECTIONS]
    if unknown:
        raise SystemExit(f"unknown injection(s): {unknown}; see INJECTIONS")
    return list(args.injection)


def section_ensure_plots(args: argparse.Namespace) -> None:
    """
    Report (and with ``--run-profit`` produce) the PROfit ``plot`` file of each injection.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    for stem in selected_stems(args):
        path = ensure_plot(stem, args.run_profit)
        print(f"{stem:10s} {path.name}  exists={path.exists()}")


def section_panels(args: argparse.Namespace) -> None:
    """
    Every injection, detector and channel as a stacked-MC data/MC panel.

    Without an injection the fake data equals the CV prediction exactly (chi2 = 0 in
    every panel, the ``ctrl`` closure). Writes
    ``<output>/<injection>/fakedata_<injection>_<detector>_<singlep|multip>.<fmt>``.
    Limit with ``--injection``, ``--channel`` and ``--detector``.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    channels = args.channel if args.channel else (0, 1)
    detectors = args.detector if args.detector else range(len(DETECTORS))
    for stem in selected_stems(args):
        if not ensure_plot(stem, args.run_profit).exists():
            print(f"{stem:10s} no histogram file, skipped")
            continue
        for channel in channels:
            for detector in detectors:
                render(stem, channel, detector, args.output, args.format)
        print(f"{stem:10s} -> {args.output / stem}")


def fake_data(
    stem: str, detector: int, channel: int, variable: int = 0
) -> tuple[np.ndarray, np.ndarray]:
    """
    Total fake-data histogram (edges, content) from a PROfit plot file.

    Parameters
    ----------
    stem : str
        Key of `INJECTIONS`.
    detector, channel : int
        Detector and channel indices.
    variable : int, optional
        Variable index.

    Returns
    -------
    edges, content : np.ndarray
        Bin edges and contents.
    """
    edges, content, _ = total_hist(
        read_hist1d(histogram_file(stem)), "DATA", detector, channel, TOTAL, variable
    )
    return edges, content


def section_osc_closure(args: argparse.Namespace) -> None:
    """
    Closure: dial route vs PROfit's own injection of the IceCube points.

    The sterile-oscillation dials (``osc_ic2024_{dm2lo,bestfit,dm2hi}``) are reBruce
    weights computed from the true neutrino energy and PDG with a **fixed 110 m
    baseline**. The same three points can be injected with PROfit's native option
    (``--inject dmsq <x> sinsq2thmm <y>``), which applies the ``numudis`` model per
    event with the event's own ``true_baseline``. The fake datasets should agree where
    the baselines agree (SBND, 110 m). In ICARUS (600 m) the dial route deliberately
    keeps 110 m, so a difference there is expected: it is the oscillation phase, not
    an error in the pipeline. Prints the largest deviation per detector, channel and
    point, and writes ``fakedata_osc_closure.<fmt>``.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    needed = [s for pair in CLOSURE_PAIRS for s in pair[:2]]
    missing = [s for s in needed if not histogram_file(s).exists()]
    if missing:
        print(f"osc-closure: missing plot files for {missing}, skipped")
        return
    fig, axes = plt.subplots(2, 3, figsize=(16, 8.5))
    rows = []
    for ch in (0, 1):
        for det in range(3):
            ax = axes[ch, det]
            for (dial_stem, phys_stem, lab), col in zip(
                CLOSURE_PAIRS, ["C0", "C1", "C2"], strict=True
            ):
                edges, a = fake_data(dial_stem, det, ch)
                _, b = fake_data(phys_stem, det, ch)
                ax.step(edges[:-1], a / b, where="post", color=col, label=lab)
                rows.append(
                    {
                        "detector": DETECTORS[det],
                        "channel": CHANNEL_TOKENS[ch],
                        "point": lab,
                        "mean dial/PROfit": float(np.mean(a / b)),
                        "max |dev|": float(np.max(np.abs(a / b - 1))),
                    }
                )
            ax.axhline(1, color="k", ls="--", lw=1)
            ax.set_title(f"{DETECTORS[det]}, {['single', 'multi'][ch]}-proton", fontsize=12)
            ax.set_xlabel("Reconstructed Neutrino Energy [GeV]", fontsize=11)
            if det == 0:
                ax.set_ylabel("dial / PROfit --inject", fontsize=11)
    axes[0, 0].legend(fontsize=9)
    for ax in axes[:, 0]:
        ax.set_ylim(0.97, 1.03)  # SBND: the two routes should agree at the percent level
    fig.subplots_adjust(hspace=0.35, wspace=0.3)
    common.save_figure(fig, args.output / f"fakedata_osc_closure.{args.format}")
    closure = pd.DataFrame(rows)
    print(
        closure.pivot_table(
            index=["detector", "channel"], columns="point", values="max |dev|", sort=False
        )
        .round(4)
        .to_string()
    )


def chi2_table(stems: list[str]) -> pd.DataFrame:
    """
    PROfit's data/MC chi2 of each injection against the CV, per detector and channel.

    Parameters
    ----------
    stems : list of str
        Injection stems; those without a plot file are skipped.

    Returns
    -------
    pandas.DataFrame
        Columns injection, detector, channel, chi2, ndf, chi2/ndf, p-value.
    """
    rows = []
    for stem in stems:
        if not histogram_file(stem).exists():
            continue
        t = uproot.open(histogram_file(stem))["chi2"].arrays(library="np")
        for det, ch, c2, ndf in zip(
            t["detector"], t["channel"], t["chi2"], t["ndf"], strict=True
        ):
            rows.append(
                {
                    "injection": stem,
                    "detector": DETECTORS[det],
                    "channel": CHANNEL_TOKENS[ch],
                    "chi2": float(c2),
                    "ndf": int(ndf),
                    "chi2/ndf": float(c2) / int(ndf),
                    "p-value": float(chi2_dist.sf(c2, ndf)),
                }
            )
    return pd.DataFrame(rows)


def section_detectability(args: argparse.Namespace) -> None:
    """
    Detectability: chi2 of each injection against the CV (full systematics).

    PROfit's data/MC chi2 for the fake data against the CV prediction with the full
    covariance, per detector and channel. Prints the chi2/ndf table and writes
    ``fakedata_chi2_summary.<fmt>`` (bars per injection, dashed line at 1).

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    table = chi2_table(selected_stems(args))
    if table.empty:
        print("detectability: no plot files found")
        return
    with pd.option_context("display.width", 200, "display.max_rows", 200):
        print(
            table.pivot_table(
                index="injection", columns=["detector", "channel"], values="chi2/ndf", sort=False
            )
            .round(2)
            .to_string()
        )
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.2), sharey=True)
    stems = [s for s in table["injection"].unique() if s != "ctrl"]
    width = 0.8 / len(DETECTORS)
    for ch, ax in enumerate(axes):
        for k, det in enumerate(DETECTORS):
            sub = (
                table[(table.channel == CHANNEL_TOKENS[ch]) & (table.detector == det)]
                .set_index("injection")
                .loc[stems]
            )
            ax.bar(np.arange(len(stems)) + k * width, sub["chi2/ndf"], width, label=det)
        ax.axhline(1, color="k", ls="--", lw=1)
        ax.set_yscale("log")
        ax.set_xticks(np.arange(len(stems)) + width)
        ax.set_xticklabels(stems, rotation=45, ha="right")
        ax.set_title(["Single-proton", "Multi-proton"][ch])
    axes[0].set_ylabel(r"$\chi^2$/ndf vs CV (full systematics)")
    axes[0].legend()
    common.save_figure(fig, args.output / f"fakedata_chi2_summary.{args.format}")


def read_global(variant: str, stem: str) -> dict:
    """
    Best-fit vector, posterior widths and chi2 of one global fit.

    Parameters
    ----------
    variant : str
        Key of `VARIANTS`.
    stem : str
        Key of `INJECTIONS`.

    Returns
    -------
    dict
        ``values`` (name -> post-fit value), ``sigma`` (name -> MCMC posterior width)
        and ``chi2`` (global best-fit chi^2 from the log, nan if absent).
    """
    tag = global_tag(variant, stem)
    values: dict[str, float] = {}
    for line in global_fit_file(variant, stem).read_text().splitlines()[1:]:
        name, _, val = line.partition(" : ")
        if val.strip():
            values[name.strip()] = float(val)
    sigma: dict[str, float] = {}
    root = uproot.open(RUNDIR / f"{TAG}_{tag}_PROglobal.root")
    for key in root.keys():
        if key.endswith("_posterior;1"):
            counts, edges = root[key].to_numpy()
            x = 0.5 * (edges[1:] + edges[:-1])
            mean = np.sum(counts * x) / counts.sum()
            sigma[key[: -len("_posterior;1")]] = float(
                np.sqrt(np.sum(counts * (x - mean) ** 2) / counts.sum())
            )
    chi2 = np.nan
    for line in (RUNDIR / "logs" / f"global_{tag}.out").read_text(errors="ignore").splitlines():
        if "Global Best Fit chi^2:" in line:
            chi2 = float(line.split("chi^2:")[1].split()[0])
    return {"values": values, "sigma": sigma, "chi2": chi2}


def pull_plot(stem: str, output: Path, fmt: str = "pdf", ntop: int = 6) -> dict[str, dict]:
    """
    Post-fit nuisance values of the floating and fixed fits for one injection.

    Pulls are post-fit nuisance values in units of the prior sigma, with the MCMC
    posterior width as the error bar; the ``ntop`` largest floating-fit pulls are
    labelled. The title quotes the oscillation point the floating fit lands on.

    Parameters
    ----------
    stem : str
        Key of `INJECTIONS`.
    output : Path
        Figure root; the plot goes to ``<output>/pulls/fakedata_pulls_<stem>.<fmt>``.
    fmt : str, optional
        File format.
    ntop : int, optional
        Number of largest pulls to label.

    Returns
    -------
    dict
        `read_global` output for each variant.
    """
    fits = {v: read_global(v, stem) for v in VARIANTS}
    names = [n for n in fits["free"]["values"] if n not in PHYSICS_NAMES]
    x = np.arange(len(names))
    fig, ax = plt.subplots(figsize=(18, 5.2))
    ax.axhspan(-1, 1, color="0.88", zorder=0, label=r"prior $\pm 1\sigma$")
    ax.axhline(0, color="k", lw=0.8)
    for v, (lab, col, off, _) in VARIANTS.items():
        y = np.array([fits[v]["values"].get(n, np.nan) for n in names])
        e = np.array([fits[v]["sigma"].get(n, np.nan) for n in names])
        ax.errorbar(
            x + off, y, yerr=e, fmt="o", ms=3.5, lw=1, color=col,
            label=f"{lab}  ($\\chi^2$ = {fits[v]['chi2']:.1f})",
        )  # fmt: skip
    yfree = np.array([fits["free"]["values"].get(n, 0.0) for n in names])
    for i in np.argsort(-np.abs(yfree))[:ntop]:
        ax.annotate(
            names[i], (x[i] - 0.15, yfree[i]), xytext=(0, 8 if yfree[i] >= 0 else -14),
            textcoords="offset points", ha="center", fontsize=8,
        )  # fmt: skip
    ax.set_xticks(x)
    ax.set_xticklabels(names, rotation=90, fontsize=6.5)
    ax.set_xlim(-1, len(names))
    ax.set_ylabel(r"post-fit value [prior $\sigma$]", fontsize=12)
    d, s22 = (10 ** fits["free"]["values"][n] for n in PHYSICS_NAMES)
    ax.set_title(
        f"{INJECTIONS[stem][1]}:  floating-fit oscillation point $\\Delta m^2$ = {d:.3g} eV$^2$, "
        f"$\\sin^2 2\\theta_{{\\mu\\mu}}$ = {s22:.3g}",
        fontsize=12,
    )
    ax.legend(loc="upper right", fontsize=9, ncol=3)
    fig.subplots_adjust(bottom=0.33, left=0.05, right=0.99)
    common.save_figure(fig, output / "pulls" / f"fakedata_pulls_{stem}.{fmt}")
    return fits


def section_pulls(args: argparse.Namespace) -> None:
    """
    Global fits of the injected points: pulls.

    A plain ``global`` fit is all a pull plot needs (no ``profile``): PROfit writes the
    best-fit vector (``*_global_fit.txt``), the covariance-mode pulls and, from its MCMC,
    a posterior for every nuisance parameter (``*_PROglobal.root``). The ``profile``
    call adds a profiled chi2 scan for every parameter, which is expensive and not
    needed here. The injected dial is excluded from the fit, so the fit has to absorb
    the fake data with the remaining nuisance parameters (and the oscillation
    parameters when they float). Two fits per injection: *floating* (nuisance and
    oscillation parameters free) and *fixed* (``--syst-only``, oscillation parameters
    held at the no-oscillation CV point).

    Writes one pull plot per injection in `FITS` that has both fits, prints the
    summary table and writes ``fakedata_pulls_summary.<fmt>``.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    stems = [s for s in FITS if not args.injection or s in args.injection]
    rows = []
    for stem in stems:
        for variant in VARIANTS:
            ensure_global(variant, stem, args.run_profit)
    for stem in stems:
        if not all(global_fit_file(v, stem).exists() for v in VARIANTS):
            print(f"{stem:10s} global fits missing, skipped")
            continue
        fr = pull_plot(stem, args.output, args.format)
        names = [n for n in fr["free"]["values"] if n not in PHYSICS_NAMES]
        d, s22 = (10 ** fr["free"]["values"][n] for n in PHYSICS_NAMES)
        rows.append(
            {
                "injection": stem,
                "chi2 floating": fr["free"]["chi2"],
                "chi2 fixed": fr["fix"]["chi2"],
                "max|pull| floating": max(abs(fr["free"]["values"][n]) for n in names),
                "max|pull| fixed": max(abs(fr["fix"]["values"][n]) for n in names),
                "fit dm2 [eV2]": d,
                "fit sin2 2th": s22,
            }
        )
    if not rows:
        print("pulls: no complete pairs of global fits found")
        return
    pulls = pd.DataFrame(rows)
    with pd.option_context("display.width", 200):
        print(pulls.round(3).to_string(index=False))
    fig, axes = plt.subplots(1, 2, figsize=(14, 4.2))
    xs = np.arange(len(pulls))
    for k, (var, col) in enumerate((("floating", "C0"), ("fixed", "C1"))):
        axes[0].bar(
            xs + (k - 0.5) * 0.4, pulls[f"chi2 {var}"], 0.4, color=col, label=f"oscillation {var}"
        )
        axes[1].bar(
            xs + (k - 0.5) * 0.4, pulls[f"max|pull| {var}"], 0.4, color=col,
            label=f"oscillation {var}",
        )  # fmt: skip
    for ax, ylab in zip(
        axes, [r"global-fit $\chi^2$", r"largest post-fit pull [prior $\sigma$]"], strict=True
    ):
        ax.set_xticks(xs)
        ax.set_xticklabels(pulls.injection, rotation=45, ha="right")
        ax.set_ylabel(ylab)
    axes[1].axhline(1, color="k", ls="--", lw=1)
    axes[0].legend()
    fig.tight_layout()
    common.save_figure(fig, args.output / f"fakedata_pulls_summary.{args.format}")


def draw_stat_only(h: dict[str, np.ndarray], chi2: dict[str, np.ndarray], label: str) -> plt.Figure:
    """
    Stat-only data/MC panel: stacked CV, fake data as points, fake/CV ratio below.

    Reads the ``hist1d`` and ``chi2`` trees of a PROfit ``plot`` file for each detector
    and channel in reconstructed energy. The grey band is the MC statistical
    uncertainty on the CV. The "data" is MC reweighted by the dial; no beam data is
    involved. This is the former ``plotting/fakedata_injection.py`` helper.

    Parameters
    ----------
    h : dict
        Output of `read_hist1d`.
    chi2 : dict
        The ``chi2`` tree as numpy arrays.
    label : str
        Injection label for the figure title.

    Returns
    -------
    matplotlib.figure.Figure
        The figure.
    """
    fig = plt.figure(figsize=(14, 10), layout=None)
    fig.set_layout_engine("none")
    gs = GridSpec(
        5, 3, height_ratios=[3, 1, 0.55, 3, 1], hspace=0.08, wspace=0.25, figure=fig,
        left=0.06, right=0.99, top=0.88, bottom=0.07,
    )  # fmt: skip
    handles, labels = [], []
    for d, dname in enumerate(DETECTORS):
        for c, cname in enumerate(STAT_CHANNELS):
            ax = fig.add_subplot(gs[3 * c, d])
            rx = fig.add_subplot(gs[3 * c + 1, d], sharex=ax)
            edges, _, _ = total_hist(h, "CV", d, c)
            bottom = np.zeros(len(edges) - 1)
            for s, (sname, col) in enumerate(STAT_SUBCHANNELS):
                _, y, _ = total_hist(h, "CV", d, c, s)
                if y.sum() <= 0:
                    continue
                ax.stairs(bottom + y, edges, baseline=bottom, fill=True, color=col, label=sname)
                bottom = bottom + y
            _, cv, cv_err = total_hist(h, "CV", d, c)
            _, dat, dat_err = total_hist(h, "DATA", d, c)
            ctr = 0.5 * (edges[1:] + edges[:-1])
            ax.stairs(cv, edges, color="k", ls="--", lw=1.2, label="CV MC")
            ax.errorbar(ctr, dat, yerr=dat_err, fmt="o", color="k", ms=3.5, label="fake data")
            safe_cv = np.where(cv > 0, cv, np.nan)
            rat = np.where(cv > 0, dat / cv, np.nan)
            rx.axhline(1, color="k", ls="--", lw=1)
            rx.stairs(
                1 + cv_err / safe_cv, edges, baseline=1 - cv_err / safe_cv, fill=True, color="0.8"
            )
            rx.errorbar(ctr, rat, yerr=dat_err / safe_cv, fmt="o", color="k", ms=3.5)
            m = (chi2["detector"] == d) & (chi2["channel"] == c)
            ax.text(
                0.97, 0.95,
                f"{dname}, {cname}\n"
                rf"$\chi^2$/ndf = {chi2['chi2'][m][0]:.1f}/{chi2['ndf'][m][0]}",
                transform=ax.transAxes, ha="right", va="top", fontsize=10,
            )  # fmt: skip
            ax.set_ylim(0, 1.3 * max(cv.max(), dat.max()))
            lim = np.nanmax(np.abs(rat - 1)) if np.isfinite(rat).any() else 0.1
            rx.set_ylim(1 - max(1.25 * lim, 0.05), 1 + max(1.25 * lim, 0.05))
            rx.set_ylabel("fake / CV")
            ax.set_ylabel("events")
            plt.setp(ax.get_xticklabels(), visible=False)
            rx.set_xlabel("reconstructed energy [GeV]")
            if d == 0 and c == 0:
                handles, labels = ax.get_legend_handles_labels()
    fig.legend(
        handles, labels, loc="upper center", ncol=len(labels), fontsize=10, frameon=False,
        bbox_to_anchor=(0.5, 0.925),
    )
    fig.suptitle(
        f"Fake data injected on CV MC: {label} (+1$\\sigma$ dial; stat. errors only)",
        y=0.985, fontsize=14,
    )  # fmt: skip
    return fig


def section_stat_only(args: argparse.Namespace) -> None:
    """
    Stat-only fake/CV panel of one PROfit plot file (not part of the default run).

    Needs ``--stat-file`` (for example
    ``runs/fakedata/fakedata_mec_PROplot_histograms.root``, made with
    ``--use-fake-data --inject-systs <dial> 1`` on ``xml/fakedata/fakedata_injection.xml``)
    and optionally ``--stat-label``. Writes ``fakedata_stat_only_<file stem>.<fmt>``.

    Parameters
    ----------
    args : argparse.Namespace
        Parsed options.
    """
    if args.stat_file is None:
        print("stat-only: pass --stat-file <PROplot_histograms.root>, skipped")
        return
    h = read_hist1d(args.stat_file)
    chi2 = uproot.open(args.stat_file)["chi2"].arrays(library="np")
    fig = draw_stat_only(h, chi2, args.stat_label or args.stat_file.stem)
    name = f"fakedata_stat_only_{args.stat_file.stem}.{args.format}"
    out = common.save_figure(fig, args.output / name)
    print("wrote", out)


class Section(NamedTuple):
    """One selectable section of the study."""

    number: int
    name: str
    func: Callable[[argparse.Namespace], None]
    title: str
    default: bool = True


#: All sections in order; ``default`` ones run when no ``--section`` is given.
SECTIONS = [
    Section(1, "ensure-plots", section_ensure_plots, "locate/run the PROfit plot steps"),
    Section(2, "panels", section_panels, "stacked CV + band + fake data + ratio panels"),
    Section(3, "osc-closure", section_osc_closure, "dial route vs PROfit native injection"),
    Section(4, "detectability", section_detectability, "chi2/ndf of each injection vs the CV"),
    Section(5, "pulls", section_pulls, "global-fit pulls of the injected points"),
    Section(6, "stat-only", section_stat_only, "stat-only panel of one file (--stat-file)", False),
]


def resolve_sections(requested: list[str] | None) -> list[Section]:
    """
    Map ``--section`` values (names or numbers) to sections.

    Parameters
    ----------
    requested : list of str or None
        Values given on the command line; None selects every default section.

    Returns
    -------
    list of Section
        The selected sections, in the order requested.

    Raises
    ------
    SystemExit
        If a value matches no section.
    """
    if not requested:
        return [s for s in SECTIONS if s.default]
    out = []
    for item in requested:
        match = [s for s in SECTIONS if item == s.name or item == str(s.number)]
        if not match:
            raise SystemExit(f"unknown section {item!r}; use --list-sections")
        out.append(match[0])
    return out


def build_parser() -> argparse.ArgumentParser:
    """
    Command-line parser.

    Returns
    -------
    argparse.ArgumentParser
        Parser with the common study options plus the section and filter options.
    """
    parser = common.base_parser(__doc__)
    parser.set_defaults(output=OUTPUT)
    parser.add_argument("--section", action="append", help="section name or number (repeatable)")
    parser.add_argument("--list-sections", action="store_true", help="list sections and exit")
    parser.add_argument(
        "--injection", action="append", help="limit to this injection stem (repeatable)"
    )
    parser.add_argument(
        "--channel", action="append", type=int, choices=(0, 1),
        help="panels: channel (0 single-proton, 1 multi-proton; repeatable)",
    )  # fmt: skip
    parser.add_argument(
        "--detector", action="append", type=int, choices=range(len(DETECTORS)),
        help="panels: detector (0 SBND, 1 ICARUS Run 2, 2 ICARUS Run 4; repeatable)",
    )  # fmt: skip
    parser.add_argument(
        "--run-profit", action="store_true",
        help="run missing PROfit plot/global steps (minutes each; off by default)",
    )  # fmt: skip
    parser.add_argument("--stat-file", type=Path, help="stat-only: PROplot histogram file")
    parser.add_argument("--stat-label", help="stat-only: injection label for the title")
    return parser


def main(argv: list[str] | None = None) -> None:
    """
    Run the selected sections.

    Parameters
    ----------
    argv : list of str, optional
        Command-line arguments; defaults to ``sys.argv[1:]``.
    """
    args = build_parser().parse_args(argv)
    if args.list_sections:
        for s in SECTIONS:
            print(f"{s.number:2d}  {s.name:14s} {s.title}{'' if s.default else '  [opt-in]'}")
        return
    sections = resolve_sections(args.section)
    common.configure_style(args.format)
    for s in sections:
        print(f"== {s.number} {s.name}: {s.title}", file=sys.stderr)
        s.func(args)


