def read_hist1d(path: Path) -> dict[str, np.ndarray]:
    """
    Read the ``hist1d`` tree of a PROfit plot file as numpy arrays.

    Parameters
    ----------
    path : Path
        PROfit ``*_PROplot_histograms.root`` file.

    Returns
    -------
    dict
        Branch name -> array; ``prefix`` is converted to a string array.
    """
    h = uproot.open(path)["hist1d"].arrays(library="np")
    h["prefix"] = np.asarray(h["prefix"]).astype(str)
    return h


def total_hist(
    h: dict[str, np.ndarray],
    prefix: str,
    detector: int,
    channel: int,
    subchannel: int = TOTAL,
    variable: int = 0,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    One histogram out of the ``hist1d`` arrays.

    Each histogram is written twice in the file; the first copy of every bin is kept.

    Parameters
    ----------
    h : dict
        Output of `read_hist1d`.
    prefix : str
        ``CV`` or ``DATA``.
    detector, channel : int
        Detector and channel indices.
    subchannel : int, optional
        Subchannel index; `TOTAL` is the channel sum.
    variable : int, optional
        Variable index.

    Returns
    -------
    edges, content, error : np.ndarray
        Bin edges (length n+1), contents and errors (length n).
    """
    m = (
        (h["variable"] == variable)
        & (h["prefix"] == prefix)
        & (h["detector"] == detector)
        & (h["channel"] == channel)
        & (h["subchannel"] == subchannel)
    )
    _, o = np.unique(h["bin_index"][m], return_index=True)
    lo, hi = h["bin_low_edge"][m][o], h["bin_high_edge"][m][o]
    return np.append(lo, hi[-1]), h["bin_content"][m][o], h["bin_error"][m][o]


