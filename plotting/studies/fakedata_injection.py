"""
Fake-data injection on the CV MC: data/MC panels, closure, detectability and pulls.

Replaces ``plotting/fakedata_injection.ipynb`` (generated by
``plotting/scripts/build_fakedata_injection_nb.py``) and absorbs the helper
``plotting/fakedata_injection.py`` (the stat-only panel, section ``stat-only``).

The plots are data/MC comparisons in the style of ``detsys/plotting/datamc.ipynb``
in which the "data" is **fake data**: the CV MC reweighted event by event by one
``spinefd`` dial (reBruce calculators evaluated on the GENIE records of our CVMC)
and injected at +1 sigma. The prediction (histogram stack and band) is the CV MC
with the **full systematics suite** of ``xml/systematics/systematics_suite.xml``.

* ``xml/fakedata/fakedata_injection_full.xml``, generated by
  ``scripts/fakedata_xml.py --full-systematics``: the suite unchanged, beam MC read
  from copy-on-write clones of the cvrw files that also hold
  ``selected_fakedataTree``, and the dials added as spline systematics used only
  for the injection.
* The fake dataset is made by PROfit itself: ``--use-fake-data --inject-systs
  multisigma_<dial> 1``. **No real beam data is read anywhere**: the XML has no
  ``<data>`` section, no ``-d`` is passed, and ``runs/fakedata_full/work/`` holds no
  data files.
* The "Data" points are the fake data with MC-statistical errors; the band is the
  total uncertainty on the CV (the dial splines are excluded from it with
  ``--exclude-systs``).
* The chi2 is PROfit's data/MC chi2 with the full covariance, so it measures how
  detectable each dial is given the systematic uncertainties, not just statistics.

Inputs (all under ``runs/fakedata_full``, written by PROfit):

* ``fdfull_<stem>_PROplot_histograms.root`` (``fdb_<stem>_...`` for the ``pl_*``
  dials): the ``plot`` step of each injection;
* ``fdfull_g<free|fix>_<stem>_global_fit.txt``, ``..._PROglobal.root`` and
  ``logs/global_...out``: the ``global`` fits used for the pull plots.

Missing ``plot``/``global`` outputs are only produced when ``--run-profit`` is given
(each ``plot`` takes minutes with the full covariance; ``process`` must already have
been run once). Without it, missing inputs are skipped and reported.

Sections (``--list-sections``, select with ``--section <name|number>``, repeatable;
default is every section except the opt-in ``stat-only``, in order):

====  ==============  ======================================================
 1    ensure-plots    run any missing PROfit ``plot`` step (``--run-profit``)
 2    panels          stacked CV + band + fake data + ratio, every panel
 3    osc-closure     dial route vs PROfit's native injection (IceCube points)
 4    detectability   chi2/ndf of each injection against the CV
 5    pulls           global-fit pulls of the injected points
 6    stat-only       stat-only fake/CV panel of one file (opt-in, --stat-file)
====  ==============  ======================================================

The "example" cells of the notebook (``ctrl``, ``mec``, ``qe``) are reproduced with
``--section panels --injection mec --channel 0 --detector 0``.

Outputs go to ``plotting/fakedata_injection_figures`` (git-ignored; ``--output`` to
change): ``<injection>/fakedata_<injection>_<detector>_<singlep|multip>.pdf``,
``fakedata_osc_closure.pdf``, ``fakedata_chi2_summary.pdf``, ``pulls/``,
``fakedata_pulls_summary.pdf``.

Technote figures: the fake-data section of ``spineosc_technote``.

Usage (mutools environment)::

    /Users/mueller/Projects/mutools/.venv/bin/python plotting/studies/fakedata_injection.py \\
        --section detectability
"""

