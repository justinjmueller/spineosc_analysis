def execute(nb):
    """Evaluate the code cells in one namespace; keep stdout and open figures as outputs."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    ns = {"__name__": "__main__"}
    for i, cell in enumerate(nb.cells):
        if cell.cell_type != "code":
            continue
        buf = io.StringIO()
        outputs = []
        try:
            with contextlib.redirect_stdout(buf):
                exec(compile(cell.source, f"<cell {i}>", "exec"), ns)
        except Exception:
            outputs.append(new_output("error", ename="Error", evalue="", traceback=traceback.format_exc().splitlines()))
            print(f"cell {i} failed:\n{traceback.format_exc()}", file=sys.stderr)
        if buf.getvalue():
            outputs.insert(0, new_output("stream", name="stdout", text=buf.getvalue()))
        for num in plt.get_fignums():
            fig = plt.figure(num)
            b = io.BytesIO()
            fig.savefig(b, format="png", dpi=110, bbox_inches="tight")
            outputs.append(new_output("display_data", data={"image/png": base64.b64encode(b.getvalue()).decode()}))
        plt.close("all")
        cell.outputs = outputs
        cell.execution_count = i
        print(f"executed cell {i}", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-exec", action="store_true")
    args = ap.parse_args()
    nb = new_notebook()
    nb.cells = [new_markdown_cell(t) if k == "md" else new_code_cell(t) for k, t in CELLS]
    if not args.no_exec:
        execute(nb)
    nbformat.write(nb, NB)
    print("wrote", NB)


if __name__ == "__main__":
    main()
