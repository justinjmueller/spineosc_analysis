md(r"""
## Global fits of the injected points: pulls

A plain **`global` fit** is all a pull plot needs (no `profile`): PROfit writes the best-fit vector (`*_global_fit.txt`),
the covariance-mode pulls and, from its MCMC, a posterior for every nuisance parameter (`*_PROglobal.root`). The
`profile` call adds a profiled chi2 scan for every parameter, which is expensive and not needed here.

The injected dial is excluded from the fit, so the fit has to absorb the fake data with the remaining nuisance
parameters (and the oscillation parameters when they float). Two fits per injection:

* **floating**: the nuisance parameters and the oscillation parameters (`dmsq`, `sin^2 2theta_mumu`) are free;
* **fixed**: `--syst-only`, oscillation parameters held at the no-oscillation CV point.

Pulls are post-fit nuisance values in units of the prior sigma, with the MCMC posterior width as the error bar.
""")

code(r'''
FITS = ['ctrl', 'mec', 'qe', 'ccqecorr', 'pifsi', 'lowq2', 'horn', 'hadprod', 'osc', 'phys_lo', 'phys_best', 'phys_hi', 'ubcc1p0pi']
VARIANTS = {'free': ('oscillation floating', 'C0', -0.15, []), 'fix': ('oscillation fixed', 'C1', 0.15, ['--syst-only'])}


def global_tag(variant, stem):
    return f'g{variant}_{stem}'


def ensure_global(variant, stem):
    tag = global_tag(variant, stem)
    out = RUNDIR / f'{TAG}_{tag}_global_fit.txt'
    if not out.exists() and RUN_PROFIT:
        profit('global', tag, stem, VARIANTS[variant][3])
    return out


def read_global(variant, stem):
    """Best-fit vector, posterior widths and chi2 of one global fit."""
    tag = global_tag(variant, stem)
    values = {}
    for line in (RUNDIR / f'{TAG}_{tag}_global_fit.txt').read_text().splitlines()[1:]:
        name, _, val = line.partition(' : ')
        if val.strip():
            values[name.strip()] = float(val)
    sigma = {}
    root = uproot.open(RUNDIR / f'{TAG}_{tag}_PROglobal.root')
    for key in root.keys():
        if key.endswith('_posterior;1'):
            counts, edges = root[key].to_numpy()
            x = 0.5 * (edges[1:] + edges[:-1])
            mean = np.sum(counts * x) / counts.sum()
            sigma[key[:-len('_posterior;1')]] = float(np.sqrt(np.sum(counts * (x - mean) ** 2) / counts.sum()))
    chi2 = np.nan
    for line in (RUNDIR / 'logs' / f'global_{tag}.out').read_text(errors='ignore').splitlines():
        if 'Global Best Fit chi^2:' in line:
            chi2 = float(line.split('chi^2:')[1].split()[0])
    return {'values': values, 'sigma': sigma, 'chi2': chi2}


for stem in FITS:
    for variant in VARIANTS:
        ensure_global(variant, stem)
print('global fits available:', {s: all((RUNDIR / f'{TAG}_{global_tag(v, s)}_global_fit.txt').exists() for v in VARIANTS) for s in FITS})
''')

